end

function writeMainParagraph(summary,outDir,support)
u = find(summary.scheme=="Uniform",1);
l = find(summary.scheme=="Loaded",1);
f = find(summary.scheme=="Fixed16",1);
if support
    outcome = 'Uniform and Loaded satisfy the pointwise upper-limit criterion; these observations support loading in this fixed model.';
elseif any(summary.statistical_status([u l])=="failed_target")
    outcome = 'Uniform or Loaded has a lower limit above the target, so their joint target-compliance comparison is unsupported.';
else
    outcome = 'The main comparison lacks sufficient target-compliance or payload-gain evidence; no reliable-rate advantage is established.';
end
paragraph = sprintf(['The author''s simplified DMT digital-baseband Monte Carlo simulation uses Hermitian mapping, ' ...
    'unitary transforms, a cyclic prefix, causal FIR convolution, and receiver-side real Gaussian noise. ' ...
    'Independent QPSK blocks estimate the channel and residual electrical symbol SNR; calibration and loading remain frozen. ' ...
    'Uniform, Loaded, and diagnostic Fixed16 share 24 subcarriers, mean symbol energy, channel, noise variance, and duration. ' ...
    'Each strategy uses three seeds with 100000 payload symbols per seed. ' ...
    'Their allocations are %g, %g, and %g bits per symbol, respectively; payload rates are %.6g, %.6g, and %.6g Mbit/s. ' ...
    'Observed bit-weighted BERs are %.6g, %.6g, and %.6g. %s ' ...
    'Fixed16 has %d subcarriers with lower limits above the target, independently diagnosing uniform higher-order modulation. ' ...
    'Intervals are approximate 95%% pointwise Wilson intervals, without simultaneous coverage; zero errors do not prove zero true BER. ' ...
    'Rates include cyclic-prefix time but exclude initialization, feedback, and FEC overhead. ' ...
    'This fixed electrical FIR model omits optical-device physics and does not establish hardware or cross-calibration performance.'], ...
    summary.B(u),summary.B(l),summary.B(f),summary.R_payload(u)/1e6,summary.R_payload(l)/1e6, ...
    summary.R_payload(f)/1e6,summary.total_BER(u),summary.total_BER(l),summary.total_BER(f), ...
    outcome,countFailed(summary.failed_target_k(f)));
words = regexp(strtrim(paragraph),'\s+','split');
assert(numel(words)>=150 && numel(words)<=200,'DMT:ParagraphLength', ...
    'Formal paragraph must contain 150--200 words (observed %d).',numel(words));
writeText(fullfile(outDir,'results_paragraph_en.txt'),paragraph);
end

function n = countFailed(text)
% Lists were generated by mat2str(integer k); parse numeric tokens only.
n = numel(regexp(char(text),'\d+','match'));
end

function writeText(path,contents)
[fid,message] = fopen(path,'w','n','UTF-8');
assert(fid>=0,'DMT:OutputOpen','Cannot open %s: %s',path,message);
closeFile = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\n',char(contents));
end

    "这个承载量比只有在主比较目标得到统计支持时，才能解释为本模型下满足约束的优势；Fixed16 的计数速率不能预先称为可靠吞吐量。"; ""; ...
    "## 三个图的趋势与诊断"; ""; ...
    "(a) 固定接收噪声下，低通 FIR 的高频幅度衰减降低电符号 SNR。估计曲线来自独立探测块 B；FIR 解析虚线仅为诊断，不输入加载器。"; ...
    "(b) Uniform 选择全部 24 个子载波均满足保守近似条件的最高公共阶数；Loaded 逐子载波选阶；Fixed16 强制全部采用 16-QAM，仅用于检验统一提高阶数的代价。图中纵轴是比特，不是功率，三者平均 Es 相同。"; ...
    "(c) Fixed16 的真实状态由计数和区间决定，不硬编码为失败；若弱子载波超标，这解释统一升阶为何可能不满足目标。失败或跨目标数据全部保留，未裁出图外。Loaded 不要求 BER 低于 Uniform，它用更密集星座交换误码余量与承载量。"; ...

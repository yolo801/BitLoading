function [perCarrier, summary, pooled, nominal] = dmt_write_outputs(cfg, calibration, profiles, runs, outDir, mode)
%DMT_WRITE_OUTPUTS Export measured counts at separate statistical levels.
% Main text/plots require all nine fixed-length runs. Smoke remains separate.
mode = validatestring(mode,{'main','smoke'});
validateRuns(cfg,profiles,runs,mode);
names = {'scheme','seed','k','frequency_Hz','SNR_est_dB','M', ...
    'bits_per_symbol','tested_bits','error_bits','BER','CI_low','CI_high','record_type'};
types = [{'string','string'} repmat({'double'},1,10) {'string'}];
perSeed = table('Size',[0 numel(names)],'VariableTypes',types,'VariableNames',names);
pooled = perSeed;
summary = table();
uniformIdx = find(strcmp({profiles.name},'Uniform'),1);
for s = 1:numel(profiles)
    profile = profiles(s);
    schemeRuns = runs(strcmp({runs.scheme},profile.name));
    pooledBits = zeros(numel(cfg.k),1);
    pooledErrors = pooledBits;
    symbols = 0; usefulEnergy = 0; cpEnergy = 0; totalEnergy = 0;
    for r = 1:numel(schemeRuns)
        one = schemeRuns(r);
        rows = carrierRows(cfg,calibration,profile,string(one.seed), ...
            one.tested_bits,one.error_bits,"seed",names);
        perSeed = [perSeed;rows]; %#ok<AGROW>
        pooledBits = pooledBits + one.tested_bits(:);
        pooledErrors = pooledErrors + one.error_bits(:);
        symbols = symbols + one.symbols;
        usefulEnergy = usefulEnergy + one.useful_energy_sum;
        cpEnergy = cpEnergy + one.cp_energy_sum;
        totalEnergy = totalEnergy + one.total_energy_sum;
    end
    rows = carrierRows(cfg,calibration,profile,"pooled",pooledBits,pooledErrors,"pooled",names);
    pooled = [pooled;rows]; %#ok<AGROW>
    intervalStatus = targetStatus(rows,cfg.targetBER);
    status = intervalStatus;
    if strcmp(mode,'smoke')
        status = "smoke_only_not_formal_evidence";
    end
    expectedUseful = 2*numel(cfg.k)*cfg.Es;
    expectedPower = expectedUseful/cfg.NFFT;
    expectedCP = expectedPower*cfg.NCP;
    expectedTotal = expectedUseful + expectedCP;
    role = "diagnostic";
    if strcmp(profile.name,'Uniform')
        role = "formal_baseline";
    elseif strcmp(profile.name,'Loaded')
        role = "formal_loaded";
    end
    failedK = string(mat2str(rows.k(rows.CI_low>cfg.targetBER).'));
    observedK = string(mat2str(rows.k(rows.BER>cfg.targetBER).'));
    uncertainK = string(mat2str(rows.k(rows.CI_low<=cfg.targetBER & rows.CI_high>=cfg.targetBER).'));
    row = table(string(profile.name),role,profile.B,profile.R_payload,sum(pooledBits), ...
        sum(pooledErrors),sum(pooledErrors)/sum(pooledBits),max(rows.BER),status,intervalStatus, ...
        usefulEnergy/symbols,cpEnergy/symbols,totalEnergy/(symbols*(cfg.NFFT+cfg.NCP)), ...
        totalEnergy/symbols,symbols,symbols*cfg.Ts,cfg.trainSymbols+cfg.probeSymbols, ...
        (cfg.trainSymbols+cfg.probeSymbols)*cfg.Ts,max(rows.CI_high), ...
        profile.B>profiles(uniformIdx).B,expectedUseful,expectedCP,expectedPower,expectedTotal, ...
        (usefulEnergy/symbols-expectedUseful)/expectedUseful, ...
        (cpEnergy/symbols-expectedCP)/expectedCP, ...
        (totalEnergy/symbols-expectedTotal)/expectedTotal, ...
        (totalEnergy/(symbols*(cfg.NFFT+cfg.NCP))-expectedPower)/expectedPower, ...
        failedK,uncertainK,observedK,numel(schemeRuns), ...
        'VariableNames',{'scheme','role','B','R_payload','total_tested_bits','total_error_bits', ...
        'total_BER','worst_subcarrier_BER','statistical_status','interval_status', ...
        'mean_useful_energy','mean_CP_energy','mean_including_CP_power', ...
        'mean_including_CP_symbol_energy','test_symbols','test_duration_s', ...
        'initialization_symbols','initialization_duration_s','maximum_CI_upper', ...
        'more_bits_than_uniform','expected_useful_energy','expected_CP_energy', ...
        'expected_including_CP_power','expected_including_CP_symbol_energy', ...
        'useful_energy_relative_difference','CP_energy_relative_difference', ...
        'total_energy_relative_difference','power_relative_difference', ...
        'failed_target_k','inconclusive_k','observed_above_target_k','test_seed_count'});
    if isempty(summary)
        summary = row;
    else
        summary = [summary;row]; %#ok<AGROW>
    end
end
u = find(summary.scheme=="Uniform",1);
l = find(summary.scheme=="Loaded",1);
gain = summary.B(l)/summary.B(u);
formalSupport = strcmp(mode,'main') && gain>1 && ...
    all(summary.statistical_status([u l])=="supported_fixed_profile");
summary.loaded_to_uniform_B_ratio = repmat(gain,height(summary),1);
summary.loaded_increase_percent = repmat(100*(gain-1),height(summary),1);
summary.main_mechanism_supported = repmat(formalSupport,height(summary),1);
% Physical separation prevents summing seed rows together with their aggregate.
perCarrier = [perSeed;pooled]; % Legacy compatibility, explicitly record_type-tagged.
nominal = pooled;
nominal.BER_design = zeros(height(pooled),1);
nominal.BER_nominal = zeros(height(pooled),1);
for s = 1:numel(profiles)
    selected = nominal.scheme==string(profiles(s).name);
    nominal.BER_design(selected) = dmt_qam_ber(profiles(s).M, ...
        calibration.gamma_hat/10^(cfg.margin_dB/10));
    nominal.BER_nominal(selected) = dmt_qam_ber(profiles(s).M,calibration.gamma_hat);
end
if strcmp(mode,'main')
    assert(height(perSeed)==216 && height(pooled)==72 && height(nominal)==72, ...
        'DMT:OutputRows','Formal output must contain 216 seed rows and 72 pooled rows.');
end
verifyPooling(perSeed,pooled);
writetable(perSeed,fullfile(outDir,'per_subcarrier_seed.csv'));
writetable(pooled,fullfile(outDir,'per_subcarrier_pooled.csv'));
writetable(nominal,fullfile(outDir,'nominal_vs_measured.csv'));
writetable(perCarrier,fullfile(outDir,'per_subcarrier_results.csv'));
writetable(summary,fullfile(outDir,'summary.csv'));
dmt_plot_results(cfg,calibration,profiles,pooled,outDir,mode);
writeNotes(cfg,calibration,pooled,summary,outDir,mode);
end

function validateRuns(cfg,profiles,runs,mode)
expectedNames = {'Uniform','Loaded','Fixed16'};
assert(numel(profiles)==3 && isequal({profiles.name},expectedNames), ...
    'DMT:Profiles','Expected profiles in order Uniform, Loaded, Fixed16.');
assert(~isempty(runs) && all(ismember({runs.scheme},expectedNames)), ...
    'DMT:NoResults','Only executed counts for the three known schemes may be exported.');
assert(isfield(runs,'phase') && all(strcmp({runs.phase},mode)), ...
    'DMT:MixedPhases','Smoke and main counts must never be combined.');
if strcmp(mode,'main')
    expectedLabels = sort(cfg.seeds);
    expectedSymbols = cfg.mainSymbols;
    assert(numel(runs)==9 && isequal(expectedLabels,[11 22 33]) && expectedSymbols==100000, ...
        'DMT:IncompleteMain','Formal outputs require all 9 frozen main runs.');
else
    expectedLabels = 0;
    expectedSymbols = cfg.smokeSymbols;
    assert(numel(runs)==3,'DMT:IncompleteSmoke','Smoke requires one run for each scheme.');
end
for s = 1:numel(profiles)
    selected = runs(strcmp({runs.scheme},profiles(s).name));
    assert(isequal(sort([selected.seed]),expectedLabels), ...
        'DMT:SeedCoverage','Missing or duplicated seed labels for %s.',profiles(s).name);
    for r = 1:numel(selected)
        one = selected(r);
        assert(one.symbols==expectedSymbols && ...
            all(one.tested_bits(:)==expectedSymbols*profiles(s).bits_per_symbol(:)), ...
            'DMT:IncompleteCounts','Incorrect symbol/bit counts for %s.',profiles(s).name);
        energy = [one.useful_energy_sum one.cp_energy_sum one.total_energy_sum];
        assert(all(isfinite(energy)) && all(energy>=0), ...
            'DMT:InvalidEnergy','Invalid measured energy counts.');
    end
end
end

function rows = carrierRows(cfg,calibration,profile,seed,bits,errors,recordType,names)
bits = double(bits(:)); errors = double(errors(:));
assert(numel(bits)==numel(cfg.k) && numel(errors)==numel(cfg.k) && ...
    all(bits>0 & errors>=0 & errors<=bits) && ...
    all(isfinite(bits) & isfinite(errors)) && all(bits==fix(bits) & errors==fix(errors)), ...
    'DMT:InvalidCounts','Invalid integer BER counts.');
[lo,hi] = dmt_wilson(errors,bits);
K = numel(cfg.k);
rows = table(repmat(string(profile.name),K,1),repmat(seed,K,1),cfg.k(:), ...
    cfg.k(:)*cfg.Fs/cfg.NFFT,calibration.gamma_hat_dB(:),profile.M(:), ...
    profile.bits_per_symbol(:),bits,errors,errors./bits,lo,hi, ...
    repmat(recordType,K,1),'VariableNames',names);
end

function status = targetStatus(rows,target)
if any(rows.CI_low>target)
    status = "failed_target";
elseif all(rows.CI_high<target)
    status = "supported_fixed_profile";
else
    status = "insufficient_evidence";
end
end

function verifyPooling(perSeed,pooled)
for i = 1:height(pooled)
    chosen = perSeed.scheme==pooled.scheme(i) & perSeed.k==pooled.k(i);
    assert(sum(perSeed.tested_bits(chosen))==pooled.tested_bits(i) && ...
        sum(perSeed.error_bits(chosen))==pooled.error_bits(i), ...
        'DMT:PoolingMismatch','Pooled rows must be the exact sum of seed rows.');
end
end


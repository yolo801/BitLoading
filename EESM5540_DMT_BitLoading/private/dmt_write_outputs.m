    "本实验是作者的简化数字基带仿真，FIR 为教学电域模型，不是实测器件。未建模光器件、偏置、非线性、削峰、量化、色散、FEC、功率加载或 PAPR；不是光硬件实验、100 Gb/s 实验或完整 Chow 算法复现，也不能推出真实数据中心光链路普遍具有相同倍数增益。"; ""; ...

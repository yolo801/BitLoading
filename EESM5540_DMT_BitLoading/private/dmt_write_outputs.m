function [perCarrier, summary] = dmt_write_outputs(cfg, calibration, profiles, runs, outDir, mode)
%DMT_WRITE_OUTPUTS Export only completed MATLAB runs, never analytical BER data.
% Counts are pooled before computing BER/intervals; total BER is bit weighted.
assert(~isempty(runs), 'DMT:NoResults', 'No executed payload runs were supplied.');
names = {'scheme','seed','k','frequency_Hz','SNR_est_dB','M', ...
    'bits_per_symbol','tested_bits','error_bits','BER','CI_low','CI_high'};
perCarrier = table('Size', [0 numel(names)], 'VariableTypes', ...
    [{'string','string'} repmat({'double'}, 1, 10)], 'VariableNames', names);
summary = table();
for s = 1:numel(profiles)
    profile = profiles(s);
    selected = strcmp({runs.scheme}, profile.name);
    schemeRuns = runs(selected);
    assert(~isempty(schemeRuns), 'DMT:MissingScheme', 'Missing executed scheme %s.', profile.name);
    pooledBits = zeros(numel(cfg.k), 1); pooledErrors = pooledBits;
    symbols = 0; usefulEnergy = 0; cpEnergy = 0; totalEnergy = 0;
    for r = 1:numel(schemeRuns)
        one = schemeRuns(r);
        assert(all(one.tested_bits(:) == one.symbols * profile.bits_per_symbol(:)), ...
            'DMT:BitCount', 'Per-carrier tested-bit count disagrees with the executed symbol count.');
        perCarrier = [perCarrier; carrierRows(cfg, calibration, profile, ...
            string(one.seed), one.tested_bits, one.error_bits, names)]; %#ok<AGROW>
        pooledBits = pooledBits + one.tested_bits(:);
        pooledErrors = pooledErrors + one.error_bits(:);
        symbols = symbols + one.symbols;
        usefulEnergy = usefulEnergy + one.useful_energy_sum;
        cpEnergy = cpEnergy + one.cp_energy_sum;
        totalEnergy = totalEnergy + one.total_energy_sum;
    end
    pooled = carrierRows(cfg, calibration, profile, "pooled", pooledBits, pooledErrors, names);
    perCarrier = [perCarrier; pooled]; %#ok<AGROW>
    if strcmpi(mode, 'smoke')
        status = "smoke_only_not_formal_evidence";
    elseif any(pooled.CI_low > cfg.targetBER)
        status = "failed_target";
    elseif all(pooled.CI_high < cfg.targetBER)
        status = "supported_fixed_profile";
    else
        status = "insufficient_evidence";
    end
    expectedUseful = 2 * numel(cfg.k) * cfg.Es;
    expectedPower = expectedUseful / cfg.NFFT;
    expectedCP = expectedPower * cfg.NCP;
    expectedTotal = expectedUseful + expectedCP;
    uniformIdx = find(strcmp({profiles.name}, 'Uniform'), 1);
    assert(~isempty(uniformIdx), 'DMT:MissingUniform', 'A Uniform profile is required.');
    row = table(string(profile.name), profile.B, profile.R_payload, sum(pooledBits), ...
        sum(pooledErrors), sum(pooledErrors)/sum(pooledBits), max(pooled.BER), status, ...
        usefulEnergy/symbols, cpEnergy/symbols, totalEnergy/(symbols*(cfg.NFFT+cfg.NCP)), ...
        totalEnergy/symbols, symbols, symbols*cfg.Ts, cfg.trainSymbols+cfg.probeSymbols, ...
        (cfg.trainSymbols+cfg.probeSymbols)*cfg.Ts, max(pooled.CI_high), min(pooled.CI_low), ...
        profile.B > profiles(uniformIdx).B, expectedUseful, expectedCP, expectedPower, ...
        expectedTotal, (usefulEnergy/symbols-expectedUseful)/expectedUseful, ...
        (cpEnergy/symbols-expectedCP)/expectedCP, ...
        (totalEnergy/symbols-expectedTotal)/expectedTotal, ...
        'VariableNames', {'scheme','B','R_payload','total_tested_bits','total_error_bits', ...
        'total_BER','worst_subcarrier_BER','statistical_status','mean_useful_energy', ...
        'mean_CP_energy','mean_including_CP_power','mean_including_CP_symbol_energy', ...
        'test_symbols','test_duration_s','initialization_symbols','initialization_duration_s', ...
        'maximum_CI_upper','minimum_CI_lower','more_bits_than_uniform', ...
        'expected_useful_energy','expected_CP_energy','expected_including_CP_power', ...
        'expected_including_CP_symbol_energy','useful_energy_relative_difference', ...
        'CP_energy_relative_difference','total_energy_relative_difference'});
    if isempty(summary)
        summary = row;
    else
        summary = [summary; row]; %#ok<AGROW>
    end
end
writetable(perCarrier, fullfile(outDir, 'per_subcarrier_results.csv'));
writetable(summary, fullfile(outDir, 'summary.csv'));
dmt_plot_results(cfg, calibration, profiles, perCarrier, outDir, mode);
writeNotes(cfg, calibration, profiles, perCarrier, summary, outDir, mode);
end

function rows = carrierRows(cfg, calibration, profile, seed, bits, errors, names)
bits = double(bits(:)); errors = double(errors(:));
assert(all(bits > 0 & errors >= 0 & errors <= bits) && ...
    all(isfinite(bits) & isfinite(errors)), 'DMT:InvalidCounts', 'Invalid BER counts.');
[lo, hi] = dmt_wilson(errors, bits);
K = numel(cfg.k);
rows = table(repmat(string(profile.name), K, 1), repmat(seed, K, 1), cfg.k(:), ...
    cfg.k(:)*cfg.Fs/cfg.NFFT, calibration.gamma_hat_dB(:), profile.M(:), ...
    profile.bits_per_symbol(:), bits, errors, errors./bits, lo, hi, 'VariableNames', names);
end

function writeNotes(cfg, calibration, profiles, perCarrier, summary, outDir, mode)
u = find(summary.scheme == "Uniform", 1); l = find(summary.scheme == "Loaded", 1);
assert(~isempty(u) && ~isempty(l), 'DMT:Schemes', 'Uniform and Loaded summaries are required.');
gain = summary.B(l)/summary.B(u);
support = all(summary.statistical_status == "supported_fixed_profile") && gain > 1;
if strcmpi(mode, 'smoke')
    conclusion = '本次仅为 smoke 程序检查，不纳入正式 BER 统计，不能作为目标 BER 验收或性能优势证据。';
elseif support
    conclusion = '在本次固定模型、一次冻结校准及 profile 下，两方案全部独立子载波的逐点 Wilson 上界低于目标；Loaded 每符号携带更多比特，统计证据支持本模型中的加载机制。';
elseif any(summary.statistical_status == "failed_target")
    conclusion = '至少一个方案有子载波的 Wilson 下界超过目标；本次结果不支持两方案均满足目标的机制结论。不得据此宣称达标优势。';
elseif gain <= 1
    conclusion = '本次 Loaded 没有携带更多比特，不能声称比特加载带来载荷速率优势。请同时检查各方案的区间验收状态。';
else
    conclusion = '至少一个方案存在跨越或触及目标的 Wilson 区间，统计证据不足；不延长测试、不换种子、不修改参数以追求通过。';
end
lines = ["# 作者的简化数字基带仿真：结果说明"; ""; ...
    "本文件仅由已完成的 MATLAB 载荷运行生成；数值来自本目录计数，不是文献数据。"; ...
    "运行模式：" + string(mode) + "。"; ""; "## 实际观察与验收"; ""; string(conclusion); ""];
for s = 1:height(summary)
    r = summary(s, :);
    lines(end+1) = string(sprintf(['%s：B=%g bits/DMT symbol，R_payload=%.9g bit/s，' ...
        '测试 %.0f 符号（%.9g s），%.0f / %.0f bit errors，' ...
        '加权总 BER=%.9g，最差子载波 BER=%.9g，最大区间上界=%.9g，状态=%s。'], ...
        char(r.scheme), r.B, r.R_payload, r.test_symbols, r.test_duration_s, ...
        r.total_error_bits, r.total_tested_bits, r.total_BER, r.worst_subcarrier_BER, ...
        r.maximum_CI_upper, char(r.statistical_status))); %#ok<AGROW>
    lines(end+1) = string(sprintf(['实际归一化电能量：有用段均值 %.9g，CP 段均值 %.9g，' ...
        '含 CP 平均功率 %.9g，含 CP 平均符号能量 %.9g；对应期望为 %g、%g、%g、%g。'], ...
        r.mean_useful_energy, r.mean_CP_energy, r.mean_including_CP_power, ...
        r.mean_including_CP_symbol_energy, r.expected_useful_energy, r.expected_CP_energy, ...
        r.expected_including_CP_power, r.expected_including_CP_symbol_energy)); %#ok<AGROW>
end
lines = [lines; ""; string(sprintf('Loaded/Uniform 的载荷比为 %.9g；估计电符号 SNR 范围 %.6g 至 %.6g dB。', ...
    gain, min(calibration.gamma_hat_dB), max(calibration.gamma_hat_dB))); ...
    string(sprintf('一次初始化为 %d 个 DMT 符号，持续 %.9g s；不计为载荷。', ...
    cfg.trainSymbols+cfg.probeSymbols, (cfg.trainSymbols+cfg.probeSymbols)*cfg.Ts)); ""; ...
    "低通 FIR 使高频子载波衰减较大，加载器根据独立探测块得到的实际估计选择阶数。低频通常允许更多比特，但必须以本次 profile 为准，不能手改为理论 118 bits。"; ...
    "Loaded 的 BER 未必比 Uniform 低：它在质量较好的子载波采用更密集星座，用误码余量换取更多比特。比较目标是同等平均 Es 和噪声条件下满足目标时的承载量，不是要求总 BER 更低。"; ""; ...
    "## 零误码与统计范围"; ""; ...
    "CSV 中 BER=0 只表示零次观察误码；对数图仅在 Wilson 上界位置画倒三角（Uniform 空心，Loaded 实心），绝不把上界当作 BER 点估计。以下逐一保留计数与上界。" ];
zerosObserved = perCarrier(perCarrier.seed == "pooled" & perCarrier.error_bits == 0, :);
if isempty(zerosObserved)
    lines(end+1) = "本次汇总子载波没有零误码项。";
else
    for r = 1:height(zerosObserved)
        row = zerosObserved(r, :);
        lines(end+1) = string(sprintf('%s k=%g: 0 observed errors / %.0f tested bits; pointwise 95%% Wilson upper=%.9g.', ...
            char(row.scheme), row.k, row.tested_bits, row.CI_high)); %#ok<AGROW>
    end
end
lines = [lines; ""; ...
    "95% Wilson 区间是常用二项近似、逐子载波的 pointwise 区间，不表示 24 个子载波同时有 95% 联合覆盖率。主实验三个种子共享一次冻结的信道估计和 profile，只验证该条件下的性能，未验证跨信道或跨初始化鲁棒性。"; ...
    "总 BER 按所有测试比特加权；不能直接平均变阶子载波的 BER。smoke 不计入 main 的计数。"; ""; ...
    "## 单位、速率及模型局限"; ""; ...
    "rho_ref=Es/sigma_w2=29 dB 只是电符号参考量；图的 SNR 是均衡后 Es/N0 口径的误差估计，不是 Eb/N0、OSNR 或时域波形 SNR。所有能量是归一化电能量，并非光功率。"; ...
    "R_payload=B/Ts 已包括 CP 时间；不扣一次初始化、反馈或 FEC，不能标为含全部开销的净吞吐量，也不能再次扣 CP。平均 Es 固定不代表峰值或含直流偏置的功率公平性。"; ...
    "该因果实 FIR 只代表端到端电域频率响应，不是器件实测数据。未建模光器件、直流光偏置、非线性、削峰、量化、色散、FEC、功率加载或 PAPR。PAPR 限制仍由报告引用的文献说明。它不是光学硬件实验、100 Gb/s 光传输复现或完整 Chow 算法。"; ""; ...
    "## 老师可能问的三个问题"; ""; ...
    "1. 为什么负频率不重复计入比特？Hermitian 镜像由正频率唯一确定，只用于产生实波形，独立载荷只有 k=1:24。"; ...
    "2. 为什么训练与探测分开？块 A 估计 H_hat，独立块 B 测量均衡残差，避免重复使用拟合数据低估残差；正式载荷不参与任何估计或调参。"; ...
    "3. 能否推论真实短距光链路也有相同比例增益？不能。这里只验证固定电域 FIR 与 AWGN 下的机制，未包括器件、光功率或完整开销，且仅共享一次冻结校准。"; ""; ...
    "## 报告与文献"; ""; ...
    "保留报告 Figure 1 的收发框图。本目录组合图可替换纯解析 Figure 2；原 abstract/report 未自动改动，最终仍需自行控制四页与四分钟。标注为作者的简化数字基带仿真，不得标为文献 Fig. 6 数据。文献 Fig. 6 绿色矩形表示功率分配，本图 (b) 只表示比特分配。"; ...
    "背景/方法参考：Zhong et al., JLT 2018, DOI 10.1109/JLT.2018.2793881；Xia et al., COMST 2017, DOI 10.1109/COMST.2016.2626784；Chow et al., TCOM 1995, DOI 10.1109/26.380108；Zhong et al., OE 2015, DOI 10.1364/OE.23.001176。本参数不是从这些文献抽取的实验参数。"];
writeText(fullfile(outDir, 'report_notes_zh.md'), join(lines, newline));

if strcmpi(mode, 'smoke')
    scope = 'This smoke run checks execution and output only; its counts are excluded from the formal three-seed statistics and cannot establish target compliance.';
else
    scope = 'Each scheme used three independent payload seeds with 100000 DMT symbols per seed, sharing one frozen calibration and profile.';
end
if support
    outcome = 'Both schemes have every pooled pointwise Wilson upper limit below the target, while loading carries more bits; these observations support the mechanism in this fixed model.';
elseif strcmpi(mode, 'smoke')
    outcome = 'No formal performance conclusion is drawn from this short run.';
elseif any(summary.statistical_status == "failed_target")
    outcome = 'At least one subcarrier has a Wilson lower limit above the target, so the experiment does not support compliance for both schemes.';
elseif gain <= 1
    outcome = 'The loaded profile does not carry more bits, so these observations do not demonstrate a payload-rate advantage.';
else
    outcome = 'At least one interval touches or crosses the target; the available statistical evidence is insufficient to support compliance for both schemes.';
end
paragraph = sprintf(['The author''s simplified DMT digital-baseband Monte Carlo simulation uses Hermitian mapping, unitary IFFT/FFT, ' ...
    'a cyclic prefix, causal FIR convolution, and receiver-side real Gaussian noise. Independent QPSK blocks estimate the channel and residual ' ...
    'electrical symbol SNR; these estimates and the selected profiles remain frozen during payload testing. ' ...
    'Uniform and loaded modulation share all 24 independent subcarriers, mean symbol energy, sampling rate, channel, and noise variance. ' ...
    '%s Uniform and loaded profiles carry %g and %g bits per DMT symbol, corresponding to %.6g and %.6g Mbit/s; ' ...
    'their observed bit-weighted BERs are %.6g and %.6g. %s ' ...
    'Error bars are approximate 95%% pointwise Wilson intervals, not simultaneous coverage; zero errors do not establish zero true BER. ' ...
    'Payload rates include cyclic-prefix time but exclude initialization, feedback, and FEC overhead. ' ...
    'This electrical FIR model omits optical-device physics and is not an optical hardware experiment or a complete Chow-algorithm reproduction.'], ...
    scope, summary.B(u), summary.B(l), summary.R_payload(u)/1e6, summary.R_payload(l)/1e6, ...
    summary.total_BER(u), summary.total_BER(l), outcome);
caption = ['Figure 2. Author''s simplified DMT digital-baseband simulation: (a) independent-probe electrical symbol SNR ' ...
    '(analytical FIR curve for diagnosis only); (b) bit allocation, not power allocation; (c) observed BER and 95% pointwise Wilson intervals. ' ...
    'Downward triangles show upper limits for zero observed errors (open: Uniform; filled: Loaded).'];
writeText(fullfile(outDir, 'results_paragraph_en.txt'), string(paragraph) + newline + newline + string(caption));
end

function writeText(path, contents)
[fid, message] = fopen(path, 'w', 'n', 'UTF-8');
assert(fid >= 0, 'DMT:OutputOpen', 'Cannot open %s: %s', path, message);
closeFile = onCleanup(@() fclose(fid));
fprintf(fid, '%s\n', char(contents));
end

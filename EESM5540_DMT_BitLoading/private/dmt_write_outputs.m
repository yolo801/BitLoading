lines = [lines; ""; ...
    "Wilson 是常用二项近似、逐点 95% 区间，不是所有子载波同时有 95% 联合覆盖保证。正式三个种子共享一次冻结的校准、profile 与信道，不代表已验证跨初始化或跨信道鲁棒性。smoke 计数不进入 main。"; ...
    string(sprintf('初始化为 %d 个符号、%.9g s，不当作载荷；每 seed 的信号时长为 %.9g s，三个 seed 汇总为 %.9g s，均非墙钟运行耗时。', ...

function report = dmt_to_checks(cfg,outDir)
%DMT_TO_CHECKS Actual MATLAB mechanical checks, separate from scientific BER.
% This function is supplied as code only; a PASS file exists only after the
% user's MATLAB actually executes these checks. Diagnostic inputs use their
% own namespace. Deliberate fixed-input replays test invariance, not new data.
assert(isfolder(outDir),'DMT:TOCheckDirectory','Create the study directory first.');
started=utcNow(); timer=tic;
rows=cell(0,1); diagnosticRows=cell(0,1); nextSeed=1800000000;
failure=[];
try
    add('fixed physical and ADC specification',cfg.NFFT==64 && cfg.NCP==8 && ...
        cfg.Fs==64e6 && isequal(cfg.k(:),(1:24).') && cfg.Es==1 && ...
        isequal(cfg.Mset,[4 16 64]) && isequal(cfg.h,[0.25 0.5 0.25]) && ...
        cfg.rho==4 && cfg.sigma_ref==sqrt(0.75) && cfg.P_peak==2 && ...
        cfg.noise_variance==1.0491e-4 && isequal(cfg.adc_range,[-0.1 2.1]), ...
        'fixed values','attachment values',0,'Mechanical parameters, not measured BER.');
    add('CP covers FIR memory',cfg.NCP>=numel(cfg.h)-1,cfg.NCP,numel(cfg.h)-1,0,'');
    add('declared symbol duration includes CP exactly once', ...
        abs(cfg.Ts-(cfg.NFFT+cfg.NCP)/cfg.Fs)<1e-18,cfg.Ts,1.125e-6,1e-18,'');

    for order=cfg.Mset
        seeds=allocate(sprintf('Gray_QAM_%d',order),false);
        M=order*ones(numel(cfg.k),1);
        [X,bits]=dmt_v13_make_frame(cfg,M,37,dmt_v13_stream(cfg,seeds.data_seed));
        x=sqrt(cfg.NFFT)*ifft(X,[],1);
        imaginary=max(abs(imag(x(:))));
        [errors,tested]=dmt_demod_errors(cfg,X(cfg.k+1,:),bits,M);
        add(sprintf('Gray QAM %d noiseless round trip',order), ...
            all(errors==0) && all(tested==37*log2(M)),sum(errors),0,0, ...
            'Direct frequency-domain unit check; not a formal payload.');
        add(sprintf('Gray QAM %d Hermitian real waveform',order), ...
            imaginary<1e-12,imaginary,0,1e-12,'Checked before real().');
        delta=max(abs(sum(abs(X).^2,1)-sum(abs(x).^2,1)));
        add(sprintf('Gray QAM %d unitary energy',order),delta<1e-10,delta,0,1e-10,'');
        add(sprintf('Gray QAM %d inactive bins remain empty',order), ...
            all(X([1 cfg.NFFT/2+1],:)==0,'all') && ...
            all(X(26:32,:)==0,'all') && all(X(34:40,:)==0,'all'), ...
            'DC, Nyquist and unassigned bins zero','zero',0,'Mirrors carry no independent bits.');
    end

    condition=struct('condition_id',1,'P_target',1,'q',8);
    seeds=allocate('DC_regression_replay',true);
    X=dmt_v13_make_frame(cfg,4*ones(24,1),64,dmt_v13_stream(cfg,seeds.data_seed));
    [newY,~,~,debug]=dmt_to_link(cfg,condition,X,1,[], ...
        dmt_v13_stream(cfg,seeds.noise_seed),true,true);
    oldCfg=cfg; oldCfg.papr_thresholds_dB=(0:0.5:18).';
    oldScenario=struct('imdd',true,'P0',1,'Pmax',2, ...
        'g',1/(cfg.rho*cfg.sigma_ref),'sigma_w2',cfg.noise_variance);
    [oldY,~,~,oldDebug]=dmt_v13_link(oldCfg,oldScenario,X,[], ...
        dmt_v13_stream(cfg,seeds.noise_seed),true,false);
    expectedP=min(cfg.P_peak,max(0,1+debug.tx_serial/(cfg.rho*cfg.sigma_ref)));
    mappingDifference=max(abs(expectedP-debug.p));
    add('b1 rho4 optical mapping matches prior model',mappingDifference<1e-13, ...
        mappingDifference,0,1e-13,'Same known sequence and clipping, ADC bypass.');
    positiveDifference=max(abs(newY(:)-oldY(:)));
    add('physical DC versus prior AC data-bin regression',positiveDifference<1e-11, ...
        positiveDifference,0,1e-11, ...
        'Deliberate replay with identical literal noise variance; old diagnostic scenario only is set to new 1.0491e-4.');
    timeDifference=reshape(debug.rx_before_adc-oldDebug.serial_rx_ac,cfg.NFFT+cfg.NCP,[]);
    usefulDifference=timeDifference(cfg.NCP+1:end,:)-1;
    add('physical versus AC difference is DC on useful samples', ...
        max(abs(usefulDifference(:)))<1e-12,max(abs(usefulDifference(:))),0,1e-12, ...
        'Initial FIR startup is inside the CP; ADC sees physical DC.');

    referenceNoise=debug.noise;
    for q=cfg.adc_bits
        another=condition; another.q=q;
        [~,~,~,one]=dmt_to_link(cfg,another,X,0.6+0.1*q,[], ...
            dmt_v13_stream(cfg,seeds.noise_seed),true,false);
        add(sprintf('fixed thermal noise replay at ADC%d',q),isequal(one.noise,referenceNoise), ...
            max(abs(one.noise-referenceNoise)),0,0, ...
            'Same noise stream deliberately replayed under different bias/ADC; no signal-based noise scaling.');
    end

    lo=cfg.adc_range(1); hi=cfg.adc_range(2);
    for q=cfg.adc_bits
        levels=2^q; step=(hi-lo)/levels;
        centers=lo+((0:levels-1)+0.5)*step;
        [actual,adc]=dmt_to_quantize(centers,q,cfg,false);
        add(sprintf('ADC%d step and distinct midpoint levels',q), ...
            adc.levels==levels && adc.step==step && numel(unique(actual))==levels && ...
            max(abs(actual-centers))<1e-14,adc.step,step,1e-14,'Uniform mid-rise, no AGC.');
        input=[lo-1 lo hi hi+1];
        [actual,adc]=dmt_to_quantize(input,q,cfg,false);
        expected=[lo+step/2 lo+step/2 hi-step/2 hi-step/2];
        add(sprintf('ADC%d saturation and strict out-of-range counts',q), ...
            max(abs(actual-expected))<1e-14 && adc.low_count==1 && adc.high_count==1 && ...
            adc.sample_count==numel(input),max(abs(actual-expected)),0,1e-14, ...
            'Exact endpoints are in range, including saturated upper-endpoint index.');
        bypass=dmt_to_quantize(input,q,cfg,true);
        add(sprintf('ADC%d bypass is an exact identity',q),isequal(input,bypass), ...
            'exact','exact',0,'Bypass is diagnostic only, not an extra formal condition.');
    end
    rejection(@()dmt_to_quantize([0 NaN],8,cfg,false), ...
        'nonfinite ADC samples rejected','DMT:TOADCInput');

    M4=4*ones(24,1); mixed=[4*ones(8,1);16*ones(8,1);64*ones(8,1)];
    firstPower=[];
    for target=cfg.P_targets
        oneCondition=condition; oneCondition.P_target=target;
        seeds=allocate(sprintf('TX_power_target_%g',target),false);
        power=dmt_to_power_cal(cfg,oneCondition,M4,seeds.data_seed);
        add(sprintf('independent fixed-waveform power calibration target %g',target), ...
            power.monotone && power.reachable && ...
            abs(power.relative_error)<=cfg.power_cal_tolerance && ...
            power.symbols==cfg.power_cal_symbols && ...
            power.sample_count==cfg.power_cal_symbols*(cfg.NFFT+cfg.NCP), ...
            power.actual_mean,target,cfg.power_cal_tolerance*target, ...
            'TX only: no noise or D/payload errors in bisection; not optical-link training time.');
        add(sprintf('bisection retains one waveform identity target %g',target), ...
            strlength(string(power.waveform_hash))==64 && ...
            numel(power.history_b)==numel(power.history_mean) && ...
            all(diff(power.monotonic_mean_grid)>=-1e-12), ...
            power.waveform_hash,'one immutable SHA-256',0,'Same generated samples for all trial b values.');
        if target==1,firstPower=power;end
    end
    seeds=allocate('TX_power_changed_complete_M',false);
    secondPower=dmt_to_power_cal(cfg,condition,mixed,seeds.data_seed);
    add('changed complete M recalibrates power on independent waveform', ...
        isequal(secondPower.M,mixed) && ~strcmp(firstPower.waveform_hash,secondPower.waveform_hash) && ...
        firstPower.seed~=secondPower.seed && abs(secondPower.relative_error)<=cfg.power_cal_tolerance, ...
        secondPower.b,'recomputed b, may numerically coincide',0, ...
        'No requirement that independent recalibration produces a different numeric b.');

    seedsA=allocate('current_M_Ar',true);
    A=dmt_to_measure(cfg,condition,mixed,secondPower.b,cfg.design_A_symbols,seedsA,'unit_Ar',[]);
    reconstructed=A.received_cross_sum./A.known_energy_sum;
    add('current-M A_r re-estimates LS from its actual known constellation', ...
        A.training && isequal(A.M,mixed) && A.symbols==cfg.design_A_symbols && ...
        max(abs(A.H_hat-reconstructed))<1e-12 && all(isnan(A.tested_bits)), ...
        max(abs(A.H_hat-reconstructed)),0,1e-12,'A_r bits are excluded from D and payload.');
    Hbefore=dmt_v13_hash(A.H_hat);
    seedsD=allocate('short_independent_D_unit_check',true);
    D=dmt_to_measure(cfg,condition,mixed,secondPower.b,257,seedsD,'unit_D_short',A.H_hat);
    [countOK,countReason]=dmt_to_count_valid(D.error_bits,D.tested_bits,mixed,D.symbols);
    add('frozen-H short diagnostic uses actual-M integer bit counts',countOK && ...
        strcmp(Hbefore,dmt_v13_hash(A.H_hat)) && isequal(D.H_used,A.H_hat), ...
        countReason,'exact current-M counts and frozen H',0, ...
        '257-symbol unit diagnostic only; real preflight and formal D budgets remain unchanged.');
    reconstructedGamma=D.known_energy_sum./D.residual_sum_sq;
    add('effective quality reconstructs from independent residual sums', ...
        max(abs(D.gamma-reconstructedGamma))<1e-10, ...
        max(abs(D.gamma-reconstructedGamma)),0,1e-10,'No equalizer refitting inside D.');

    replayCfg=cfg; replayCfg.chunkSize=127;
    replay=dmt_to_measure(replayCfg,condition,mixed,secondPower.b,257,seedsD,'unit_D_replay',A.H_hat);
    additive={'tx_sum','tx_sum_sq','drive_ac_sq_sum','useful_energy_sum','cp_energy_sum', ...
        'total_energy_sum','noise_sum','noise_sum_sq'};
    invariant=isequal(D.error_bits,replay.error_bits) && isequal(D.tested_bits,replay.tested_bits) && ...
        D.metrics.sample_count==replay.metrics.sample_count && ...
        D.metrics.lower_clip_count==replay.metrics.lower_clip_count && ...
        D.metrics.upper_clip_count==replay.metrics.upper_clip_count && ...
        D.metrics.adc_low_count==replay.metrics.adc_low_count && ...
        D.metrics.adc_high_count==replay.metrics.adc_high_count;
    for j=1:numel(additive)
        field=additive{j}; invariant=invariant && ...
            abs(D.metrics.(field)-replay.metrics.(field))<=1e-10*max(1,abs(D.metrics.(field)));
    end
    add('symbol/noise/FIR/ADC counters invariant across chunk replay',invariant, ...
        '257 as 257 versus 127+127+3','same frozen input',0, ...
        'Deliberate replay, not a new independent block or a change to frozen ChunkSymbols.');

    supports=true(24,1); supports(3)=false;
    [next,blocked,changed]=dmt_to_reduce(cfg,64*ones(24,1),supports,'UniformAdaptive');
    add('Uniform fallback lowers the entire table',~blocked && changed && all(next==16), ...
        mat2str(next.'),'all 16-QAM',0,'Synthetic support mask, not measured D.');
    [next,blocked,changed]=dmt_to_reduce(cfg,64*ones(24,1),supports,'ValidatedLoading');
    expected=64*ones(24,1);expected(3)=16;
    add('Loaded fallback lowers unsupported carriers only',~blocked && changed && isequal(next,expected), ...
        mat2str(next.'),mat2str(expected.'),0,'Synthetic support mask, not measured D.');
    decision=dmt_to_decide(cfg,M4,supports,'ValidatedLoading',1);
    add('unsupported minimum order does not become an accepted table', ...
        strcmp(decision.status,'no_accepted_profile_min_order') && ...
        decision.terminal && ~decision.accepted && isempty(decision.next_M), ...
        decision.status,'no_accepted_profile_min_order',0,'');
    decision=dmt_to_decide(cfg,64*ones(24,1),supports,'UniformAdaptive',cfg.max_rounds);
    add('round-budget exhaustion rejects unprobed next table', ...
        strcmp(decision.status,'round_budget_exhausted') && ...
        decision.terminal && ~decision.accepted && isempty(decision.next_M), ...
        decision.status,'round_budget_exhausted',0,'Synthetic last-round support mask.');
    decision=dmt_to_decide(cfg,64*ones(24,1),supports,'ValidatedLoading',1);
    add('changed full table requires a new complete validation round', ...
        strcmp(decision.status,'retest') && ~decision.accepted && ~decision.terminal && ...
        isequal(decision.next_M,expected),decision.status,'retest',0, ...
        'Previously supported carriers are not an accepted partial-table cache.');
    decision=dmt_to_decide(cfg,M4,true(24,1),'UniformAdaptive',cfg.max_rounds);
    add('actually supported last round remains eligible for acceptance', ...
        strcmp(decision.status,'accepted') && decision.accepted && decision.terminal && ...
        isequal(decision.next_M,M4),decision.status,'accepted',0,'Synthetic all-supported mask.');

    emptyDesign=struct('status','round_budget_exhausted');
    rejection(@()dmt_to_payload(cfg,condition,emptyDesign,seedsD,cfg.preflight_payload_symbols), ...
        'rejected design cannot launch payload','DMT:TONoAcceptedProfile');
    fixture=struct('status','accepted','condition',condition,'M',mixed,'b',secondPower.b, ...
        'H_hat',A.H_hat,'final_tx',struct(),'final_rx',struct(), ...
        'ack',struct('accepted',false,'configuration_hash','wrong'));
    rejection(@()dmt_to_payload(cfg,condition,fixture,seedsD,cfg.preflight_payload_symbols), ...
        'missing/mismatched ACK cannot launch payload','DMT:TOMissingACK');
    invalidTx=struct('M',mixed,'b',secondPower.b,'q',condition.q, ...
        'adc_range',cfg.adc_range,'H_hash',dmt_v13_hash(A.H_hat), ...
        'power_hash','invalid_guard_fixture_not_a_scientific_record', ...
        'validation_hash','invalid_guard_fixture_not_a_scientific_record', ...
        'profile_id','unit_guard_fixture');
    fixture.final_tx=invalidTx;fixture.final_rx=invalidTx;
    fixture.ack=struct('accepted',true,'configuration_hash',dmt_v13_hash(invalidTx));
    fixture.b=secondPower.b+0.01;
    rejection(@()dmt_to_payload(cfg,condition,fixture,seedsD,cfg.preflight_payload_symbols), ...
        'changed bias cannot bypass frozen configuration','DMT:TOFrozenConfiguration');
    fixture.b=secondPower.b;fixture.H_hat=A.H_hat*1.001;
    rejection(@()dmt_to_payload(cfg,condition,fixture,seedsD,cfg.preflight_payload_symbols), ...
        'changed receiver estimate cannot bypass frozen configuration','DMT:TOFrozenConfiguration');

    [ok,~]=dmt_to_count_valid([],[],M4,2000);
    add('missing raw counters never become zero-error completion',~ok,ok,false,0,'Synthetic count rejection.');
    [ok,~]=dmt_to_count_valid(zeros(24,1),2000*log2(M4),M4,2000);
    add('exact finite synthetic counters accepted by count invariant',ok,ok,true,0,'Only tests the counter helper.');
    bad=zeros(24,1);bad(1)=NaN;
    [ok,~]=dmt_to_count_valid(bad,2000*log2(M4),M4,2000);
    add('nonfinite error counters rejected',~ok,ok,false,0,'');
    bad=zeros(24,1);bad(1)=4001;
    [ok,~]=dmt_to_count_valid(bad,2000*log2(M4),M4,2000);
    add('errors above tested bits rejected',~ok,ok,false,0,'');
    [ok,~]=dmt_to_count_valid(zeros(24,1),2000*log2(M4)+1,M4,2000);
    add('tested bits inconsistent with actual M and symbols rejected',~ok,ok,false,0,'');
    [low,high]=dmt_wilson(D.error_bits,D.tested_bits);
    z=1.96; p=D.error_bits./D.tested_bits; den=1+z*z./D.tested_bits;
    center=(p+z*z./(2*D.tested_bits))./den;
    rad=sqrt(p.*(1-p)./D.tested_bits+z*z./(4*D.tested_bits.^2))*z./den;
    difference=max([abs(low-max(0,center-rad));abs(high-min(1,center+rad))]);
    add('Wilson independently reconstructs from short diagnostic raw counts', ...
        difference<1e-14,difference,0,1e-14,'Approximate pointwise interval, not formal BER acceptance.');
    [~,zeroHigh]=dmt_wilson(0,8192*2);
    add('zero observed errors retain positive interval upper endpoint', ...
        abs(zeroHigh-z*z/(8192*2+z*z))<1e-16 && zeroHigh>0, ...
        zeroHigh,z*z/(8192*2+z*z),1e-16,'Synthetic zero count only.');

    formal=dmt_to_plan(cfg,'formal'); preflight=dmt_to_plan(cfg,'preflight');
    allSeeds=[formal.data_seed;formal.noise_seed;preflight.data_seed;preflight.noise_seed];
    allSeeds=allSeeds(isfinite(allSeeds));
    diagSeeds=[];
    if ~isempty(diagnosticRows)
        diagnostic=vertcat(diagnosticRows{:});
        diagSeeds=[diagnostic.data_seed;diagnostic.noise_seed];diagSeeds=diagSeeds(isfinite(diagSeeds));
    end
    add('all planned role streams and diagnostic namespace are separate', ...
        numel(unique(allSeeds))==numel(allSeeds) && isempty(intersect(allSeeds,diagSeeds)) && ...
        numel(unique(diagSeeds))==numel(diagSeeds),numel(allSeeds),numel(unique(allSeeds)),0, ...
        'A0/B0 are shared by lookup, not duplicated plan rows; TX-power-cal has no noise stream.');
    pure=ismember(string(formal.role),["initial_power" "power"]);
    add('TX-only power calibration has no fictional noise seed', ...
        all(isnan(formal.noise_seed(pure))) && all(isfinite(formal.noise_seed(~pure))), ...
        sum(pure),'noise-free TX roles',0,'');
catch ME
    failure=ME;
    add('unexpected mechanical-check exception',false,ME.identifier,'no exception',0,ME.message);
end
checks=vertcat(rows{:});
diagnostic=table();if ~isempty(diagnosticRows),diagnostic=vertcat(diagnosticRows{:});end
report=struct('protocol',cfg.protocol,'passed',all(checks.passed), ...
    'checks',checks,'diagnostic_seeds',diagnostic,'started_utc',started, ...
    'finished_utc',utcNow(),'compute_seconds',toc(timer),'matlab_version',version, ...
    'config_id',dmt_v13_hash(cfg),'formal_payload_symbols_executed',0, ...
    'interpretation','Mechanical diagnostics/replays only; not formal scientific evidence.');
save(fullfile(outDir,'mechanical_checks.mat'),'report');
writetable(checks,fullfile(outDir,'mechanical_checks.csv'));
fid=fopen(fullfile(outDir,'mechanical_checks.txt'),'w','n','UTF-8');assert(fid>=0);
cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'Actual MATLAB mechanical checks | %s | passed=%d | checks=%d\n', ...
    report.finished_utc,report.passed,height(checks));
fprintf(fid,'Diagnostic/replay streams are not preflight or formal BER samples.\n');
for j=1:height(checks)
    fprintf(fid,'%d | %s | observed=%s | expected=%s | %s\n',checks.passed(j), ...
        checks.name(j),checks.observed(j),checks.expected(j),checks.note(j));
end
if ~isempty(failure),rethrow(failure);end
assert(report.passed,'DMT:TradeoffMechanicalChecksFailed', ...
    'Mechanical checks failed. Preserve reports; do not freeze the formal protocol.');

    function seeds=allocate(role,noise)
        nextSeed=nextSeed+10;
        seeds=struct('data_seed',nextSeed+1,'noise_seed',NaN);
        if noise,seeds.noise_seed=nextSeed+2;end
        diagnosticRows{end+1,1}=table(string(role),seeds.data_seed,seeds.noise_seed, ...
            'VariableNames',{'role','data_seed','noise_seed'});
    end

    function add(name,passed,observed,expected,tolerance,note)
        rows{end+1,1}=table(string(name),logical(passed),asText(observed),asText(expected), ...
            tolerance,string(note),'VariableNames',{'name','passed','observed','expected','tolerance','note'});
        fprintf('TO MECHANICAL | %d | %s\n',passed,name);
    end

    function rejection(call,name,identifier)
        rejected=false; observed='no exception';
        try,call();catch ME,rejected=strcmp(ME.identifier,identifier);observed=ME.identifier;end
        add(name,rejected,observed,identifier,0,'Guard test; no accepted scientific profile manufactured.');
    end
end

function value=asText(value)
if ischar(value)||isstring(value),value=string(value);
elseif isnumeric(value)||islogical(value),value=string(mat2str(value));
else,value=string(jsonencode(value));end
end

function value=utcNow()
value=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd HH:mm:ss.SSS Z'));
end

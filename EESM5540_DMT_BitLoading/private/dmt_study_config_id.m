function id = dmt_study_config_id(cfg)
% Paths/timestamps are provenance; the frozen scientific configuration is hashed.
fields = {'NFFT','NCP','Fs','k','h','Es','sigma_w2','Mset','targetBER', ...
    'margin_dB','trainSymbols','probeSymbols','mainSymbols','chunkSize', ...
    'seeds','NumCalibrations','selfTrainSeed','selfPayloadSeeds','selfNoiseSeed'};
parts = ["DMT study protocol="+string(cfg.protocolVersion); ...
    "physical="+string(cfg.specVersion);"stream="+string(cfg.streamType); ...
    "new_seed_base=2000000+100000*calibration_id; payload uses slot=1:3"];
for j = 1:numel(fields)
    value = cfg.(fields{j});
    parts(end+1,1) = string(fields{j})+"["+string(sprintf('%d,',size(value)))+"]="+ ...
        string(sprintf('%.17g,',value(:))); %#ok<AGROW>
end
id = dmt_sha256(join(parts,newline));
end

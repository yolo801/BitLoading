function [valid,reason] = dmt_v13_validate_run(cp,cfg,scenario,record,s,label,phase,expectedMeta)
%DMT_V13_VALIDATE_RUN Resume only a fully completed, ACK-protected fixed group.
% A performance failure is valid evidence. An optical mean investigation flag
% is retained rather than corrected by rescaling or selecting another seed.
valid=false; reason='';
try
    require(isstruct(cp) && isscalar(cp),'Checkpoint must be a scalar structure.');
    require(all(isfield(cp,{'state','config_id','source_id','seed_map_id','record_hash','run_hash','run'})), ...
        'Missing configuration, source, calibration or count identities.');
    require(strcmp(string(cp.state),"complete"),'The group must explicitly be marked complete.');
    compareMeta(cp,expectedMeta);
    require(ismember(s,1:3) && isscalar(s),'Unknown strategy index.');
    require(ismember(label,[11 22 33]) && isscalar(label),'Unknown payload label.');
    require(any(strcmp(string(phase),["formal" "preflight"])),'Unknown run phase.');
    require(record.configured && record.scenario_idx==scenario.scenario_idx && ...
        textEqual(record.scenario_id,scenario.scenario_id),'Missing configured calibration.');
    require(textEqual(cp.record_hash,dmt_v13_hash(record)), ...
        'Saved group calibration/control record identity differs.');
    if isfield(expectedMeta,'record_hash')
        require(textEqual(cp.record_hash,expectedMeta.record_hash),'Unexpected parent record hash.');
    end
    tx=record.exchange.tx_profiles(s);
    rx=record.exchange.rx_profiles(s);
    ack=record.exchange.acks(s);
    require(logicalScalar(tx.feasible) && logicalScalar(rx.feasible) && ...
        logicalScalar(ack.accepted) && tx.feasible && rx.feasible && ack.accepted, ...
        'A group cannot exist for an infeasible or unacknowledged configuration.');
    configurationHash=dmt_v13_hash(tx);
    require(textEqual(configurationHash,dmt_v13_hash(rx)) && ...
        textEqual(configurationHash,ack.configuration_hash), ...
        'TX, RX and ACK configuration identities differ.');
    run=cp.run;
    fields={'scenario_idx','scenario_id','calibration_id','scheme','profile_id', ...
        'configuration_hash','record_hash','data_seed','noise_seed','seed','phase', ...
        'symbols','tested_bits','error_bits','useful_energy_sum','cp_energy_sum', ...
        'total_energy_sum','sample_count','optical_applicable','optical_sum', ...
        'optical_sum_sq','optical_peak','optical_min','lower_clip_count', ...
        'upper_clip_count','clip_error_sq_sum','papr_thresholds_dB', ...
        'papr_exceed_counts','papr_symbols','signal_duration_s', ...
        'optical_mean','optical_second_moment','optical_ac_variance', ...
        'optical_mean_relative_deviation','power_mean_investigation_required', ...
        'clipping_rate','clip_error_mean_square'};
    require(isstruct(run) && isscalar(run) && all(isfield(run,fields)), ...
        'Incomplete completed-group counter record.');
    require(run.scenario_idx==scenario.scenario_idx && ...
        textEqual(run.scenario_id,scenario.scenario_id) && ...
        run.calibration_id==record.calibration_id && ...
        textEqual(run.scheme,tx.scheme) && textEqual(run.profile_id,tx.profile_id) && ...
        textEqual(run.configuration_hash,configurationHash) && ...
        textEqual(run.record_hash,cp.record_hash), ...
        'Actual run does not belong to this scenario, calibration or profile.');
    require(textEqual(run.phase,phase) && run.seed==label,'Run phase or seed label differs.');
    n=cfg.payloadSymbols;
    if strcmp(string(phase),'preflight'), n=cfg.preflightSymbols; end
    require(integerScalar(run.symbols) && run.symbols==n,'Run has incomplete actual symbols.');
    require(ismember(record.calibration_id,1:10),'Unknown calibration ID.');
    if strcmp(string(phase),'preflight')
        require(record.calibration_id==1,'Preflight uses one calibration per scenario.');
    end
    slot=find([11 22 33]==label);
    base=2000000+10000000*scenario.scenario_idx+100000*record.calibration_id;
    if strcmp(string(phase),'preflight'), base=base+100000000; end
    require(run.data_seed==base+1000*s+10*slot+1 && ...
        run.noise_seed==base+1000*s+10*slot+2,'Run random streams differ from the fixed plan.');
    M=tx.M_k;
    require(isequal(size(M),[24 1]) && all(ismember(M,cfg.Mset)) && ...
        isequal(rx.M_k,M) && isequal(tx.bits_k,log2(M)) && isequal(rx.bits_k,log2(M)), ...
        'Accepted local QAM profiles do not agree.');
    require(isequal(size(run.tested_bits),[24 1]) && ...
        all(run.tested_bits==n*log2(M)), ...
        'Tested bits do not match actual symbols and independent carriers.');
    require(isequal(size(run.error_bits),[24 1]) && isreal(run.error_bits) && ...
        all(isfinite(run.error_bits) & run.error_bits>=0 & ...
        run.error_bits<=run.tested_bits & run.error_bits==fix(run.error_bits)), ...
        'Invalid integer error counters.');
    samples=(cfg.NFFT+cfg.NCP)*n;
    require(run.sample_count==samples && run.papr_symbols==n,'Incorrect sample/PAPR denominator.');
    energy=[run.useful_energy_sum run.cp_energy_sum run.total_energy_sum];
    require(isreal(energy) && all(isfinite(energy) & energy>=0),'Invalid input electrical energies.');
    near(run.total_energy_sum,run.useful_energy_sum+run.cp_energy_sum, ...
        'Useful and CP energy do not sum to total.');
    near(run.signal_duration_s,n*cfg.Ts,'Signal duration differs from symbol count.');
    require(isequal(run.papr_thresholds_dB,cfg.papr_thresholds_dB(:)), ...
        'PAPR threshold grid changed.');
    counts=run.papr_exceed_counts;
    require(isequal(size(counts),size(cfg.papr_thresholds_dB(:))) && ...
        all(isfinite(counts) & counts>=0 & counts<=n & counts==fix(counts)) && ...
        all(diff(counts)<=0),'Invalid sampled AC PAPR CCDF exceedance counts.');
    clips=[run.lower_clip_count run.upper_clip_count];
    require(all(isfinite(clips) & clips>=0 & clips==fix(clips)) && ...
        sum(clips)<=samples,'Invalid lower/upper clipping counts.');
    require(scalarFinite(run.clip_error_sq_sum) && run.clip_error_sq_sum>=0, ...
        'Invalid clipping error power sum.');
    near(run.clipping_rate,sum(clips)/samples,'Clipping rate differs from counts.');
    near(run.clip_error_mean_square,run.clip_error_sq_sum/samples, ...
        'Mean clipping error differs from the actual sum.');
    require(logicalScalar(run.optical_applicable) && ...
        logical(run.optical_applicable)==logical(scenario.imdd),'Optical applicability is inconsistent.');
    if scenario.imdd
        powers=[run.optical_sum run.optical_sum_sq run.optical_peak run.optical_min];
        require(isreal(powers) && all(isfinite(powers)) && ...
            run.optical_min>=-1e-12 && run.optical_peak<=scenario.Pmax+1e-12 && ...
            run.optical_peak>=run.optical_min && run.optical_sum>=0 && ...
            run.optical_sum<=scenario.Pmax*samples+1e-9 && run.optical_sum_sq>=0, ...
            'Saved normalized optical power violates the sampled [0,Pmax] range.');
        meanPower=run.optical_sum/samples;
        second=run.optical_sum_sq/samples;
        require(meanPower>=run.optical_min-1e-12 && meanPower<=run.optical_peak+1e-12 && ...
            second>=meanPower^2-1e-10 && second<=scenario.Pmax*meanPower+1e-10, ...
            'Optical first and second moments are inconsistent.');
        near(run.optical_mean,meanPower,'Mean optical power differs.');
        near(run.optical_second_moment,second,'Optical second moment differs.');
        near(run.optical_ac_variance,max(0,second-meanPower^2),'Optical AC variance differs.');
        deviation=meanPower/scenario.P0-1;
        near(run.optical_mean_relative_deviation,deviation,'Mean optical-power deviation differs.');
        require(logicalScalar(run.power_mean_investigation_required) && ...
            logical(run.power_mean_investigation_required)==(abs(deviation)>0.01), ...
            'A greater-than-one-percent mean-power deviation was not reported correctly.');
    else
        optical=[run.optical_sum run.optical_sum_sq run.optical_peak run.optical_min ...
            run.optical_mean run.optical_second_moment run.optical_ac_variance ...
            run.optical_mean_relative_deviation];
        require(all(isnan(optical)) && all(clips==0) && run.clip_error_sq_sum==0 && ...
            ~run.power_mean_investigation_required, ...
            'Linear electrical model must not invent optical-power measurements.');
    end
    require(textEqual(cp.run_hash,dmt_v13_hash(run)),'Completed-group content hash differs.');
    valid=true;
    reason='complete fixed group; configuration ACK, counters, power and PAPR metadata verified';
    if scenario.imdd && run.power_mean_investigation_required
        reason=[reason '; actual mean optical power needs investigation, with no rescaling'];
    end
catch ME
    reason=ME.message;
end
end

function compareMeta(cp,expected)
for field={'config_id','source_id','seed_map_id'}
    name=field{1};
    require(isfield(expected,name) && textEqual(cp.(name),expected.(name)), ...
        ['Checkpoint identity differs: ' name]);
end
end

function require(condition,message)
assert(isscalar(condition) && logical(condition),'DMT:InvalidV13Run','%s',message);
end

function same=textEqual(a,b)
a=string(a); b=string(b);
same=isscalar(a) && isscalar(b) && ~ismissing(a) && ~ismissing(b) && a==b;
end

function yes=scalarFinite(value)
yes=isnumeric(value) && isreal(value) && isscalar(value) && isfinite(value);
end

function yes=integerScalar(value)
yes=scalarFinite(value) && value>=0 && value==fix(value);
end

function yes=logicalScalar(value)
yes=(islogical(value) || isnumeric(value)) && isscalar(value) && ...
    isreal(value) && isfinite(value) && ismember(value,[0 1]);
end

function near(a,b,message)
require(isnumeric(a) && isnumeric(b) && isreal(a) && isreal(b) && ...
    isequal(size(a),size(b)) && all(isfinite(a(:))) && all(isfinite(b(:))),message);
require(all(abs(double(a(:))-double(b(:)))<=1e-12+1e-10*abs(double(b(:)))),message);
end

function [valid,reason] = dmt_v13_validate_record(cp,cfg,scenario,cid,phase,expectedMeta)
%DMT_V13_VALIDATE_RECORD Verify frozen A/B, ideal control copies and probe C.
% This never creates new observations, updates estimates or tunes a profile.
% Fixed16 remains a valid diagnostic configuration if Uniform/Loaded cannot
% form a complete feasible table. Performance failures are not data damage.
valid=false; reason='';
try
    require(isstruct(cp) && isscalar(cp) && ...
        all(isfield(cp,{'config_id','source_id','seed_map_id','record_hash','record'})), ...
        'Incomplete calibration/control checkpoint metadata.');
    for key={'config_id','source_id','seed_map_id'}
        name=key{1};
        require(isfield(expectedMeta,name) && textEqual(cp.(name),expectedMeta.(name)), ...
            ['Checkpoint identity differs: ' name]);
    end
    require(isscalar(cid) && ismember(cid,1:10),'Invalid calibration ID.');
    require(any(strcmp(string(phase),["formal" "preflight"])),'Unknown record phase.');
    if strcmp(string(phase),'preflight'), require(cid==1,'Preflight uses calibration 1 only.'); end
    record=cp.record;
    required={'scenario_idx','scenario_id','calibration_id','configured', ...
        'observations','receiver','exchange','probes'};
    require(isstruct(record) && isscalar(record) && all(isfield(record,required)), ...
        'Incomplete frozen record.');
    require(record.scenario_idx==scenario.scenario_idx && ...
        textEqual(record.scenario_id,scenario.scenario_id) && record.calibration_id==cid && ...
        logicalScalar(record.configured) && logical(record.configured), ...
        'Calibration record belongs to another scenario or is not configured.');
    require(textEqual(cp.record_hash,dmt_v13_hash(record)), ...
        'Frozen record contents do not match their external SHA-256.');
    base=2000000+10000000*scenario.scenario_idx+100000*cid;
    if strcmp(string(phase),'preflight'), base=base+100000000; end
    obs=record.observations;
    fields={'scenario_idx','scenario_id','calibration_id','active_k','Es_reference', ...
        'symbols_A','symbols_B','X_A','Y_A','X_B','Y_B','seeds','phase','sample_hash'};
    require(isstruct(obs) && isscalar(obs) && all(isfield(obs,fields)), ...
        'Missing A/B observation sources.');
    require(obs.scenario_idx==scenario.scenario_idx && ...
        textEqual(obs.scenario_id,scenario.scenario_id) && obs.calibration_id==cid && ...
        textEqual(obs.phase,phase) && isequal(obs.active_k,cfg.k(:)) && ...
        obs.Es_reference==cfg.Es,'A/B scenario, phase or reference energy differs.');
    require(obs.symbols_A==1024 && obs.symbols_A==cfg.trainSymbols && ...
        obs.symbols_B==2048 && obs.symbols_B==cfg.probeSymbols,'A/B lengths differ.');
    require(all(isfield(obs.seeds,{'A_data_seed','A_noise_seed','B_data_seed','B_noise_seed'})), ...
        'Missing independent A/B stream metadata.');
    require(isequal([obs.seeds.A_data_seed obs.seeds.A_noise_seed ...
        obs.seeds.B_data_seed obs.seeds.B_noise_seed],base+[101 102 201 202]), ...
        'A/B random streams differ from the fixed scenario/calibration map.');
    require(textEqual(obs.sample_hash,dmt_v13_hash(rmfield(obs,'sample_hash'))), ...
        'A/B sample identity does not match saved observations.');
    validateMatrix(obs.X_A,[24 1024],'A known samples');
    validateMatrix(obs.Y_A,[24 1024],'A received samples');
    validateMatrix(obs.X_B,[24 2048],'B known samples');
    validateMatrix(obs.Y_B,[24 2048],'B received samples');
    qpsk=1/sqrt(2);
    require(all(abs(abs(real(obs.X_A(:)))-qpsk)<1e-12) && ...
        all(abs(abs(imag(obs.X_A(:)))-qpsk)<1e-12) && ...
        all(abs(abs(real(obs.X_B(:)))-qpsk)<1e-12) && ...
        all(abs(abs(imag(obs.X_B(:)))-qpsk)<1e-12), ...
        'A/B must be the prescribed known unit-average-power QPSK samples.');
    rx=record.receiver;
    fields={'scenario_idx','scenario_id','calibration_id','active_k','Es_reference', ...
        'H_hat','gamma_B','gamma_B_dB','training_denominator','probe_signal_sum', ...
        'probe_residual_sum','estimator_version','observation_hash','quality_kind', ...
        'phase','calibration_hash'};
    require(isstruct(rx) && isscalar(rx) && all(isfield(rx,fields)), ...
        'Incomplete receiver-only estimation record.');
    require(rx.scenario_idx==scenario.scenario_idx && textEqual(rx.scenario_id,scenario.scenario_id) && ...
        rx.calibration_id==cid && textEqual(rx.phase,phase) && ...
        isequal(rx.active_k,cfg.k(:)) && rx.Es_reference==cfg.Es, ...
        'Receiver estimate belongs to another configuration.');
    require(textEqual(rx.observation_hash,obs.sample_hash) && ...
        textEqual(rx.calibration_hash,dmt_v13_hash(rmfield(rx,'calibration_hash'))), ...
        'Receiver calibration does not match the actual A/B source or its hash.');
    denominator=sum(abs(obs.X_A).^2,2);
    Hhat=sum(obs.Y_A.*conj(obs.X_A),2)./denominator;
    signal=sum(abs(obs.X_B).^2,2);
    residual=sum(abs(obs.Y_B./Hhat-obs.X_B).^2,2);
    require(all(abs(Hhat)>0) && all(residual>0),'Invalid independently estimated channel/residual.');
    near(rx.H_hat,Hhat,'Receiver channel does not equal A-only LS estimate.');
    near(rx.training_denominator,denominator,'Receiver training denominator differs.');
    near(rx.probe_signal_sum,signal,'Receiver B signal sum differs.');
    near(rx.probe_residual_sum,residual,'Receiver B residual sum differs.');
    near(rx.gamma_B,signal./residual,'Receiver quality must use independent B.');
    near(rx.gamma_B_dB,10*log10(signal./residual),'Receiver linear/dB quality differs.');

    ex=record.exchange;
    fields={'scenario_idx','scenario_id','calibration_id','feedback_sent','feedback_received', ...
        'feedback_hash_sent','feedback_hash_received','tx_profiles','rx_profiles', ...
        'acks','candidate_predictions','allocation_recomputed'};
    require(isstruct(ex) && isscalar(ex) && all(isfield(ex,fields)), ...
        'Missing explicit feedback/configuration exchange.');
    require(ex.scenario_idx==scenario.scenario_idx && textEqual(ex.scenario_id,scenario.scenario_id) && ...
        ex.calibration_id==cid,'Control exchange scenario/calibration differs.');
    sent=ex.feedback_sent; received=ex.feedback_received;
    feedbackFields={'scenario_idx','scenario_id','calibration_id','active_k', ...
        'gamma_hat_linear','Es_reference','estimator_version','calibration_hash','phase'};
    require(all(isfield(sent,feedbackFields)) && isequaln(sent,received), ...
        'Ideal feedback copies differ or omit required quality fields.');
    forbidden={'H_hat','H_true','gamma_true','X_A','Y_A','X_B','Y_B', ...
        'noise','error_bits','tested_bits','payload_BER'};
    require(~any(isfield(sent,forbidden)) && ~any(isfield(received,forbidden)), ...
        'Tx quality feedback leaked receiver channel/raw data or payload results.');
    require(sent.scenario_idx==scenario.scenario_idx && textEqual(sent.scenario_id,scenario.scenario_id) && ...
        sent.calibration_id==cid && isequal(sent.active_k,cfg.k(:)) && ...
        sent.Es_reference==cfg.Es && textEqual(sent.phase,phase) && ...
        textEqual(sent.calibration_hash,rx.calibration_hash) && ...
        textEqual(sent.estimator_version,rx.estimator_version), ...
        'Feedback identity/reference differs from receiver quality.');
    near(sent.gamma_hat_linear,rx.gamma_B,'Feedback quality differs from frozen B estimate.');
    feedbackHash=dmt_v13_hash(sent);
    require(textEqual(ex.feedback_hash_sent,feedbackHash) && ...
        textEqual(ex.feedback_hash_received,dmt_v13_hash(received)) && ...
        textEqual(ex.feedback_hash_received,feedbackHash),'Ideal feedback hashes differ.');
    require(logicalScalar(ex.allocation_recomputed) && ex.allocation_recomputed, ...
        'Independent allocation check was not recorded.');
    design=zeros(24,numel(cfg.Mset)); nominal=design;
    for j=1:numel(cfg.Mset)
        design(:,j)=approx(cfg.Mset(j),sent.gamma_hat_linear/10^(cfg.margin_dB/10));
        nominal(:,j)=approx(cfg.Mset(j),sent.gamma_hat_linear);
    end
    legal=design<=cfg.targetBER;
    feasible=all(any(legal,2));
    expectedOrders={zeros(0,1),zeros(0,1),16*ones(24,1)};
    if feasible
        expectedOrders{1}=max(cfg.Mset(all(legal,1)))*ones(24,1);
        expectedOrders{2}=zeros(24,1);
        for k=1:24, expectedOrders{2}(k)=max(cfg.Mset(legal(k,:))); end
    end
    require(numel(ex.tx_profiles)==3 && numel(ex.rx_profiles)==3 && numel(ex.acks)==3, ...
        'Three separate local strategy configurations and ACKs are required.');
    require(iscell(record.probes) && numel(record.probes)==3,'Expected three C diagnostic slots.');
    names={'Uniform','Loaded','Fixed16'};
    for s=1:3
        tx=ex.tx_profiles(s); local=ex.rx_profiles(s); ack=ex.acks(s);
        configFields={'scenario_id','scenario_idx','calibration_id','profile_id','scheme', ...
            'active_k','M_k','bits_k','Gray_mapping_version','Es_reference','targetBER', ...
            'margin_dB','calibration_hash','feasible','reason','B','R_payload','phase'};
        require(all(isfield(tx,configFields)) && isequaln(tx,local), ...
            'Tx and Rx local configuration objects differ.');
        canConfigure=s==3 || feasible;
        require(logicalScalar(tx.feasible) && logical(tx.feasible)==canConfigure && ...
            textEqual(tx.scheme,names{s}) && tx.scenario_idx==scenario.scenario_idx && ...
            textEqual(tx.scenario_id,scenario.scenario_id) && tx.calibration_id==cid && ...
            textEqual(tx.phase,phase) && isequal(tx.active_k,cfg.k(:)) && ...
            tx.Es_reference==cfg.Es && tx.targetBER==cfg.targetBER && ...
            tx.margin_dB==cfg.margin_dB && textEqual(tx.calibration_hash,rx.calibration_hash), ...
            'Local profile identity, scope or feasibility differs.');
        require(isfield(cfg,'gray_mapping_version') && ...
            textEqual(tx.Gray_mapping_version,cfg.gray_mapping_version), ...
            'Unknown Gray mapping/version convention.');
        require(isequal(tx.M_k,expectedOrders{s}) && isequal(tx.bits_k,log2(expectedOrders{s})), ...
            'Tx allocation differs from an independent reconstruction of saved feedback.');
        hash=dmt_v13_hash(tx);
        ackFields={'accepted','configuration_hash','scenario_idx','scenario_id','calibration_id','profile_id'};
        require(all(isfield(ack,ackFields)) && logicalScalar(ack.accepted) && ...
            logical(ack.accepted)==canConfigure && textEqual(ack.configuration_hash,hash) && ...
            ack.scenario_idx==scenario.scenario_idx && textEqual(ack.scenario_id,scenario.scenario_id) && ...
            ack.calibration_id==cid && textEqual(ack.profile_id,tx.profile_id), ...
            'Missing or inconsistent ideal receiver ACK.');
        if canConfigure
            near(tx.B,sum(log2(expectedOrders{s})),'Profile bit count differs.');
            near(tx.R_payload,tx.B/cfg.Ts,'Profile payload rate differs.');
            validateProbe(record.probes{s},tx,ack,rx,cfg,scenario,cid,base,s);
        else
            require(isempty(record.probes{s}) && isnan(tx.B) && isnan(tx.R_payload) && ...
                strlength(string(tx.reason))>0, ...
                'Infeasible strategy must keep a reason and have no invented C samples/rate.');
        end
    end
    predictions=ex.candidate_predictions;
    cols={'k','M','gamma_B','gamma_B_dB','BER_design','BER_nominal','design_feasible'};
    require(istable(predictions) && height(predictions)==24*numel(cfg.Mset) && ...
        all(ismember(cols,predictions.Properties.VariableNames)), ...
        'Missing per-candidate Tx BER predictions.');
    for j=1:numel(cfg.Mset)
        rows=sortrows(predictions(predictions.M==cfg.Mset(j),:),'k');
        require(height(rows)==24 && isequal(rows.k,cfg.k(:)),'Incomplete candidate frequency rows.');
        near(rows.gamma_B,rx.gamma_B,'Candidate quality differs.');
        near(rows.gamma_B_dB,rx.gamma_B_dB,'Candidate dB quality differs.');
        near(rows.BER_design,design(:,j),'Candidate conservative BER differs.');
        near(rows.BER_nominal,nominal(:,j),'Candidate nominal BER differs.');
        require(all(isfinite(double(rows.design_feasible))) && ...
            all(ismember(double(rows.design_feasible),[0 1])) && ...
            isequal(logical(rows.design_feasible),legal(:,j)),'Candidate feasibility flags differ.');
    end
    valid=true;
    reason='A/B sources, receiver-only estimates, ideal feedback/local ACKs and independent C verified';
catch ME
    reason=ME.message;
end
end

function validateProbe(probe,tx,ack,rx,cfg,scenario,cid,base,s)
fields={'scenario_idx','scenario_id','calibration_id','scheme','profile_id', ...
    'configuration_hash','calibration_hash','data_seed','noise_seed','symbols', ...
    'active_k','gamma_B','gamma_C','gamma_B_dB','gamma_C_dB','delta_dB', ...
    'EVM_rms','signal_sum','residual_sum','BER_nominal_B','BER_nominal_C', ...
    'BER_design_B','BER_design_C','candidate_predictions','probe_hash','phase'};
require(isstruct(probe) && isscalar(probe) && all(isfield(probe,fields)), ...
    'Missing independent accepted-profile C diagnostic.');
require(probe.scenario_idx==scenario.scenario_idx && textEqual(probe.scenario_id,scenario.scenario_id) && ...
    probe.calibration_id==cid && textEqual(probe.scheme,tx.scheme) && ...
    textEqual(probe.profile_id,tx.profile_id) && ...
    textEqual(probe.configuration_hash,ack.configuration_hash) && ...
    textEqual(probe.calibration_hash,rx.calibration_hash) && textEqual(probe.phase,rx.phase), ...
    'C belongs to another frozen receiver or accepted profile.');
require(probe.symbols==2048 && probe.symbols==cfg.validationSymbols && ...
    probe.data_seed==base+5000+100*s+1 && probe.noise_seed==base+5000+100*s+2 && ...
    isequal(probe.active_k,cfg.k(:)),'C length, independent streams or active carriers differ.');
require(textEqual(probe.probe_hash,dmt_v13_hash(rmfield(probe,'probe_hash'))), ...
    'C source/statistics digest differs.');
for field={'gamma_C','signal_sum','residual_sum'}
    value=probe.(field{1});
    require(isequal(size(value),[24 1]) && isreal(value) && ...
        all(isfinite(value) & value>0),'Invalid positive independent C statistics.');
end
gamma=probe.signal_sum./probe.residual_sum;
near(probe.gamma_B,rx.gamma_B,'C comparison must preserve B quality.');
near(probe.gamma_C,gamma,'C quality differs from actual residual sums.');
near(probe.gamma_B_dB,10*log10(rx.gamma_B),'C saved B dB quality differs.');
near(probe.gamma_C_dB,10*log10(gamma),'C dB quality differs.');
near(probe.delta_dB,10*log10(gamma)-10*log10(rx.gamma_B),'C/B quality difference differs.');
near(probe.EVM_rms,sqrt(probe.residual_sum./probe.signal_sum),'C EVM differs.');
near(probe.BER_nominal_B,approx(tx.M_k,rx.gamma_B),'C actual-profile nominal B prediction differs.');
near(probe.BER_nominal_C,approx(tx.M_k,gamma),'C actual-profile nominal C prediction differs.');
near(probe.BER_design_B,approx(tx.M_k,rx.gamma_B/10^(cfg.margin_dB/10)), ...
    'C actual-profile design B prediction differs.');
near(probe.BER_design_C,approx(tx.M_k,gamma/10^(cfg.margin_dB/10)), ...
    'C actual-profile design C prediction differs.');
table=probe.candidate_predictions;
required={'k','M','BER_nominal_B','BER_nominal_C','BER_design_B','BER_design_C'};
require(istable(table) && height(table)==24*numel(cfg.Mset) && ...
    all(ismember(required,table.Properties.VariableNames)),'Missing C candidate predictions.');
for j=1:numel(cfg.Mset)
    rows=sortrows(table(table.M==cfg.Mset(j),:),'k');
    require(height(rows)==24 && isequal(rows.k,cfg.k(:)),'C candidate carrier rows differ.');
    near(rows.BER_nominal_B,approx(cfg.Mset(j),rx.gamma_B),'C candidate nominal B differs.');
    near(rows.BER_nominal_C,approx(cfg.Mset(j),gamma),'C candidate nominal C differs.');
    near(rows.BER_design_B,approx(cfg.Mset(j),rx.gamma_B/10^(cfg.margin_dB/10)), ...
        'C candidate design B differs.');
    near(rows.BER_design_C,approx(cfg.Mset(j),gamma/10^(cfg.margin_dB/10)), ...
        'C candidate design C differs.');
end
end

function p=approx(M,gamma)
p=4./log2(M).*(1-1./sqrt(M)).*0.5.*erfc(sqrt(3*gamma./(M-1))/sqrt(2));
end

function validateMatrix(value,shape,label)
require(isnumeric(value) && isequal(size(value),shape) && all(isfinite(value(:))), ...
    ['Invalid ' label ' dimensions or finite values.']);
end

function require(condition,message)
assert(isscalar(condition) && logical(condition),'DMT:InvalidV13Record','%s',message);
end

function same=textEqual(a,b)
a=string(a); b=string(b);
same=isscalar(a) && isscalar(b) && ~ismissing(a) && ~ismissing(b) && a==b;
end

function yes=logicalScalar(value)
yes=(islogical(value) || isnumeric(value)) && isscalar(value) && ...
    isreal(value) && isfinite(value) && ismember(value,[0 1]);
end

function near(a,b,message)
require(isnumeric(a) && isnumeric(b) && isequal(size(a),size(b)) && ...
    all(isfinite(a(:))) && all(isfinite(b(:))),message);
require(all(abs(double(a(:))-double(b(:)))<=1e-12+1e-10*abs(double(b(:)))),message);
end

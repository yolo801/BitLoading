function probe = dmt_v13_probe_c(cfg,scenario,receiver,txConfig,rxConfig,ack,seeds)
%DMT_V13_PROBE_C Independent profile-matched diagnostic; never adapts a table.
assert(cfg.validationSymbols==2048 && cfg.chunkSize>=1 && cfg.chunkSize<=2000);
assert(txConfig.feasible && rxConfig.feasible && ack.accepted, ...
    'DMT:V13ProbeNeedsACK','Validation C requires an accepted complete configuration.');
configurationHash = dmt_v13_hash(txConfig);
assert(strcmp(configurationHash,dmt_v13_hash(rxConfig)) && ...
    strcmp(configurationHash,ack.configuration_hash));
assert(strcmp(txConfig.scenario_id,scenario.scenario_id) && ...
    txConfig.scenario_idx==scenario.scenario_idx && ...
    txConfig.calibration_id==receiver.calibration_id && ...
    strcmp(txConfig.calibration_hash,receiver.calibration_hash));
assert(strcmp(receiver.calibration_hash,dmt_v13_hash(rmfield(receiver,'calibration_hash'))), ...
    'DMT:V13CalibrationHash','Validation C cannot use a modified receiver estimate.');
assert(isequal(rxConfig.M_k,txConfig.M_k) && isequal(rxConfig.active_k,cfg.k(:)));
assert(seeds.data_seed~=seeds.noise_seed);
schemeNames = {'Uniform','Loaded','Fixed16'};
s = find(strcmp(schemeNames,txConfig.scheme));
assert(isscalar(s) && ismember(string(receiver.phase),["formal" "preflight"]));
base = 2000000+10000000*scenario.scenario_idx+100000*receiver.calibration_id;
if strcmp(receiver.phase,'preflight'), base=base+100000000; end
assert(seeds.data_seed==base+5000+100*s+1 && ...
    seeds.noise_seed==base+5000+100*s+2,'DMT:V13ProbeSeeds', ...
    'Validation C needs its own fixed stream pair, independent of A/B and payload.');
receiverBefore = dmt_v13_hash(receiver);
dataStream = dmt_v13_stream(cfg,seeds.data_seed);
noiseStream = dmt_v13_stream(cfg,seeds.noise_seed);
signalSum = zeros(24,1); residualSum = signalSum;
state = []; done = 0;
while done<cfg.validationSymbols
    count = min(cfg.chunkSize,cfg.validationSymbols-done);
    X = dmt_v13_make_frame(cfg,txConfig.M_k,count,dataStream);
    [Y,~,state] = dmt_v13_link(cfg,scenario,X,state,noiseStream,true);
    known = X(cfg.k+1,:);
    equalized = Y./receiver.H_hat;
    signalSum = signalSum+sum(abs(known).^2,2);
    residualSum = residualSum+sum(abs(equalized-known).^2,2);
    done = done+count;
end
assert(all(isfinite(signalSum) & signalSum>0) && ...
    all(isfinite(residualSum) & residualSum>0));
gammaC = signalSum./residualSum;
gammaB = receiver.gamma_B;
probe = struct('scenario_idx',scenario.scenario_idx,'scenario_id',scenario.scenario_id, ...
    'calibration_id',receiver.calibration_id,'scheme',txConfig.scheme, ...
    'profile_id',txConfig.profile_id,'configuration_hash',configurationHash, ...
    'calibration_hash',receiver.calibration_hash,'data_seed',seeds.data_seed, ...
    'noise_seed',seeds.noise_seed,'symbols',done,'active_k',cfg.k(:), ...
    'gamma_B',gammaB,'gamma_C',gammaC,'gamma_B_dB',10*log10(gammaB), ...
    'gamma_C_dB',10*log10(gammaC),'delta_dB',10*log10(gammaC)-10*log10(gammaB), ...
    'EVM_rms',sqrt(residualSum./signalSum),'signal_sum',signalSum, ...
    'residual_sum',residualSum,'quality_kind',receiver.quality_kind,'phase',receiver.phase, ...
    'BER_nominal_B',dmt_qam_ber(txConfig.M_k,gammaB), ...
    'BER_nominal_C',dmt_qam_ber(rxConfig.M_k,gammaC), ...
    'BER_design_B',dmt_qam_ber(txConfig.M_k,gammaB/10^(cfg.margin_dB/10)), ...
    'BER_design_C',dmt_qam_ber(rxConfig.M_k,gammaC/10^(cfg.margin_dB/10)));
predictions = table();
for j = 1:numel(cfg.Mset)
    M = cfg.Mset(j);
    rows = table(cfg.k(:),repmat(M,24,1),dmt_qam_ber(M,gammaB), ...
        dmt_qam_ber(M,gammaC),dmt_qam_ber(M,gammaB/10^(cfg.margin_dB/10)), ...
        dmt_qam_ber(M,gammaC/10^(cfg.margin_dB/10)), ...
        'VariableNames',{'k','M','BER_nominal_B','BER_nominal_C','BER_design_B','BER_design_C'});
    if isempty(predictions), predictions=rows; else, predictions=[predictions;rows]; end %#ok<AGROW>
end
probe.candidate_predictions = predictions;
probe.interpretation = ['C minus B also contains finite probing variation and channel-estimation residual; ' ...
    'it cannot be attributed entirely to QAM order or clipping. C is excluded from payload BER.'];
assert(strcmp(receiverBefore,dmt_v13_hash(receiver)) && ...
    strcmp(configurationHash,dmt_v13_hash(txConfig)) && ...
    strcmp(configurationHash,dmt_v13_hash(rxConfig)), ...
    'DMT:V13ProbeModifiedState','Validation C modified a frozen receiver or configuration.');
probe.probe_hash = dmt_v13_hash(probe);
end

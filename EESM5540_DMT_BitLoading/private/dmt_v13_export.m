function writeEnglish(cfg,out,outDir)
requested=unique(out.summary.scenario_idx(out.summary.requested_scope));
observations=strings(0,1);
for q=requested(:).'
    u=out.robustness(out.robustness.scenario_idx==q & out.robustness.scheme=="Uniform",:);
    l=out.robustness(out.robustness.scenario_idx==q & out.robustness.scheme=="Loaded",:);
    f=out.robustness(out.robustness.scenario_idx==q & out.robustness.scheme=="Fixed16",:);
    observations(end+1,1)=string(sprintf(['For %s, Uniform/Loaded/Fixed16 were supported in %d/%d/%d calibrations; ' ...
        'Loaded allocated %s--%s bits per symbol.'],char(l.scenario_id),u.supported,l.supported,f.supported, ...
        show(l.B_min),show(l.B_max))); %#ok<AGROW>
end
paragraph=sprintf(['The author''s explicit-feedback DMT simulation separates receiver quality estimation, ideal SNR feedback, ' ...
    'transmitter allocation, independent configuration copies, and receiver acknowledgement. Independent QPSK blocks estimate ' ...
    'the channel and effective quality; a configuration-specific probe C diagnoses transfer without updating the frozen profiles. ' ...
    'Within the requested scope, %d of %d planned payload groups completed, while %d were infeasible; no incomplete groups are treated as successful. ' ...
    'Each completed group contains %d DMT symbols. %s ' ...
    'Only three payload seeds within the same scenario, calibration, strategy, and subcarrier are pooled. ' ...
    'Approximate pointwise Wilson intervals are a common evidence criterion, not simultaneous coverage; zero errors do not prove zero true BER. ' ...
    'Allocated rate ratios are described as supported gains only when both Uniform and Loaded satisfy the criterion in that calibration. ' ...
    'The normalized IM/DD front end keeps bias and peak limits fixed while AC drive and sampled clipping vary together. ' ...
    'Rates include cyclic-prefix time but exclude initialization, feedback, and FEC. ' ...
    'These fixed-model observations do not establish actual optical-device performance or future calibration success probabilities.'], ...
    out.requested_completed_groups,out.requested_planned_groups,out.requested_infeasible_groups, ...
    cfg.payloadSymbols,char(join(observations," ")));
writeText(fullfile(outDir,'results_paragraph_en.txt'),paragraph);
end

function writeCaptions(outDir,phase)
prefix='Formal payload data.';
if strcmp(phase,'preflight'), prefix='Preflight only; excluded from formal statistics.'; end
captions=[string(prefix);""; ...
    "Closed-loop transceiver. Solid arrows show forward samples; dashed arrows show ideal control information. H remains at the receiver; quality feedback, transmitter allocation, separate local configuration copies and ACK are explicit. Bias/clipping is a normalized discrete-time IM/DD equivalent, with signaling overhead not modeled.";""; ...
    "Linear calibration 1. (a) Independent QPSK probe-B quality; (b) the accepted bit allocation; (c) pointwise 95% Wilson approximate upper endpoint divided by the BER target. All panels use the preselected same new calibration, not reference 0 or a best selected round. The criterion is 1; an upper endpoint above 1 alone does not establish a lower-bound target violation. Intervals do not provide simultaneous coverage. The detailed observed-BER plot is separate.";""; ...
    "IM/DD summary. Sample clipping is measured across actual completed groups; allocated bits show calibration median and min-max range, not a 95% band. Support labels give supported/complete calibration counts. All rho conditions share P0=1 and Pmax=2; rho varies AC drive and clipping jointly, so nominal rates are not universally compliant net throughput.";""; ...
    "Sampled AC PAPR before bias/clipping, preselected calibration 1. Curves retain their actual exceedance counts and symbol denominators; zero counts remain 0/N in CSV and are omitted on the logarithmic axis. AC amplitude scaling itself does not imply PAPR improvement.";""; ...
    "Independent validation probe C minus probe B effective quality, preselected calibration 1. Differences include finite-probe fluctuation, channel-estimation residual and possible nonlinear configuration dependence. Each acknowledged strategy uses 2048 independent known symbols; no C samples enter formal BER or alter a profile.";""; ...
    "Only figures listed as written in figure_manifest.csv were generated; a caption is not evidence that unavailable data or a figure exists."];
writeText(fullfile(outDir,'figure_caption_en.txt'),join(captions,newline));
end

function text=show(value)
text='missing'; if isfinite(value), text=sprintf('%.9g',value); end
end

function writeText(path,text)
[fid,message]=fopen(path,'w','n','UTF-8'); assert(fid>=0,'DMT:OutputOpen','%s',message);
cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\n',char(text));
end

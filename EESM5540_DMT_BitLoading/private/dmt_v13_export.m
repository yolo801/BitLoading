function out = dmt_v13_export(cfg,records,runs,outDir,phase,renderPlots)
%DMT_V13_EXPORT Export only actual v1.3 counts and clearly separated scopes.
assert(isfolder(outDir));
if nargin<6,renderPlots=true;end
out=dmt_v13_tables(cfg,records,runs,phase);
writetable(out.seed,fullfile(outDir,'per_calibration_seed.csv'));
writetable(out.pooled,fullfile(outDir,'per_calibration_pooled.csv'));
writetable(out.summary,fullfile(outDir,'per_calibration_summary.csv'));
writetable(out.run_status,fullfile(outDir,'run_status.csv'));
writetable(out.robustness,fullfile(outDir,'robustness_summary.csv'));
writetable(out.profile_frequency,fullfile(outDir,'profile_frequency.csv'));
writetable(out.power,fullfile(outDir,'power_clipping_metrics.csv'));
writetable(out.papr,fullfile(outDir,'papr_ccdf_counts.csv'));
writetable(out.probe_C,fullfile(outDir,'validation_probe_C.csv'));
out.requested_scope_resolved=out.requested_incomplete_groups==0;
out.all_formal_slots_resolved=strcmp(phase,'formal') && out.incomplete_groups==0;
out.all_360_completed=strcmp(phase,'formal') && out.completed_groups==360;
out.plots_completed=false;
out.figures=table();
if renderPlots && out.requested_scope_resolved
    try
        out.figures=dmt_v13_plots(cfg,records,runs,out,outDir,phase);
        out.plots_completed=true;
    catch ME
        fid=fopen(fullfile(outDir,'figure_export_error.txt'),'a');
        if fid>=0
            fprintf(fid,'%s\n',getReport(ME,'extended','hyperlinks','off'));
            fclose(fid);
        end
        out.figures=table("export_batch","failed",string(ME.message), ...
            'VariableNames',{'figure','status','interpretation'});
        writetable(out.figures,fullfile(outDir,'figure_manifest.csv'));
        fprintf(2,'Figure export failed; actual counts and CSVs retained: %s\n',ME.message);
    end
else
    out.figures=table("export_batch","deferred","No plot is claimed current for this interim count export.", ...
        'VariableNames',{'figure','status','interpretation'});
    writetable(out.figures,fullfile(outDir,'figure_manifest.csv'));
end
writeChinese(cfg,out,outDir);
writeCaptions(outDir,phase);
if out.mean_power_alert_groups>0
    writeText(fullfile(outDir,'mean_power_investigation_required.txt'), ...
        sprintf(['%d completed formal groups have |mean(p)/P0-1| > 1%%. ' ...
        'Investigate statistics/implementation before accepting the power budget. ' ...
        'Do not rescale or delete the recorded data.'],out.mean_power_alert_groups));
end
if renderPlots && strcmp(phase,'formal') && out.requested_scope_resolved && ...
        out.requested_completed_groups>0 && out.mean_power_alert_groups==0
    writeEnglish(cfg,out,outDir);
elseif strcmp(phase,'preflight')
    writeText(fullfile(outDir,'preflight_notes_en.txt'), ...
        'Preflight only. These short counts are excluded from all formal payload statistics.');
elseif isfile(fullfile(outDir,'results_paragraph_en.txt'))
    % A new requested scope must not inherit an earlier scope's completed text.
    stamp=char(datetime('now','TimeZone','UTC','Format','yyyyMMdd_HHmmss_SSS'));
    movefile(fullfile(outDir,'results_paragraph_en.txt'), ...
        fullfile(outDir,['previous_scope_results_paragraph_' stamp '.txt']));
end
fprintf('v1.3 %s export: actual %d / all-plan %d groups; requested %d/%d, infeasible %d, incomplete %d.\n', ...
    phase,out.completed_groups,out.planned_groups,out.requested_completed_groups, ...
    out.requested_planned_groups,out.requested_infeasible_groups,out.requested_incomplete_groups);
end


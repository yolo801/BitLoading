function dmt_t2_check(kind,data,cfg,condition,calID,scheme,slot,phase,plan,parent)
%DMT_T2_CHECK Audit a v2 record and its parent without sending any symbols.
assert(isscalar(data) && isstruct(data) && isequaln(data.condition,condition) && ...
    data.calibration_id==calID && strcmp(data.phase,phase), ...
    'DMT:V2RecordIdentity','Wrong phase, condition or calibration in %s.',kind);

switch kind
    case 'Shared'
        legacyCheck();
    case 'Design'
        assert(strcmp(data.scheme,scheme),'DMT:V2DesignIdentity','Wrong strategy in design record.');
        if strcmp(data.status,'power_error')
            assert(isfield(data,'reason') && strlength(string(data.reason))>0 && ...
                isempty(data.M),'DMT:V2PowerError','Power error cannot authorize payload.');
        elseif strcmp(scheme,'ValidatedLoading')
            legacyCheck();
            assert(isstruct(parent) && strcmp(parent.status,'complete') && ...
                strcmp(data.initial_shared_hash,dmt_v13_hash(parent)) && ...
                isequal(data.initial_gamma_B,parent.gamma_B), ...
                'DMT:V2SharedJoin','Loaded design is detached from its saved shared probe.');
        else
            checkFixed(data,cfg,condition,calID,scheme,phase,plan);
        end
    case 'Payload'
        legacyCheck();
        assert(isstruct(parent) && any(strcmp(parent.status,{'fixed_authorized','accepted'})) && ...
            strcmp(data.design_hash,dmt_v13_hash(parent)) && ...
            strcmp(data.configuration_hash,dmt_v13_hash(parent.final_tx)) && ...
            strcmp(data.profile_id,parent.final_tx.profile_id) && ...
            isequal(data.M,parent.M) && isequal(data.M_rx,parent.M) && ...
            data.b==parent.b && isequal(data.H_used,parent.H_hat), ...
            'DMT:V2PayloadJoin','Payload does not use its authorized, frozen configuration.');
    otherwise
        error('DMT:V2RecordKind','Unknown v2 record kind: %s.',kind);
end

    function legacyCheck()
        % The isolated v1 numerical validators still apply to the retained
        % A0/B0 and D_r loading protocol, and to the actual payload counters.
        [ok,reason]=dmt_to_validate(kind,data,cfg,condition,calID,scheme,slot,phase,plan);
        assert(ok,'DMT:V2RecordSemantics','%s: %s',kind,reason);
    end
end

function checkFixed(d,cfg,c,cal,scheme,phase,plan)
assert(any(strcmp(scheme,{'FixedQPSK','Fixed64QAM'})) && strcmp(d.status,'fixed_authorized') && ...
    strcmp(d.authorization_basis,'fixed_profile_sync'), ...
    'DMT:V2FixedAuthorization','Unexpected fixed-strategy authorization.');
order=4;
if strcmp(scheme,'Fixed64QAM'),order=64;end
M=repmat(order,numel(cfg.k),1);
power=d.power;
training=d.Ar;
pSeed=dmt_to_seed(plan,c.condition_id,cal,scheme,1,'power',NaN);
aSeed=dmt_to_seed(plan,c.condition_id,cal,scheme,1,'Ar',NaN);
assert(isequal(d.M,M) && isequal(power.M,M) && isequal(training.M,M) && ...
    isequal(training.M_rx,M) && d.b==power.b && training.b==power.b, ...
    'DMT:V2FixedTable','Fixed modulation order or calibrated coefficient changed.');
assert(power.seed==pSeed.data_seed && isnan(pSeed.noise_seed) && ...
    power.symbols==cfg.power_cal_symbols && ...
    power.sample_count==power.symbols*(cfg.NFFT+cfg.NCP) && ...
    power.reachable && power.monotone && power.target==c.P_target && ...
    isfinite(power.actual_mean) && abs(power.actual_mean/c.P_target-1)<=cfg.power_cal_tolerance && ...
    power.b>=cfg.b_bounds(1) && power.b<=cfg.b_bounds(2) && ...
    ~isempty(regexp(power.waveform_hash,'^[0-9a-f]{64}$','once')), ...
    'DMT:V2FixedPower','Fixed power calibration failed its frozen stream or power tolerance.');
assert(isfield(d,'power_reused') && isscalar(d.power_reused) && islogical(d.power_reused), ...
    'DMT:V2FixedPowerReuse','Saved power-calibration reuse flag is invalid.');
assert(training.training && strcmp(training.role,'Ar') && isempty(training.H_used) && ...
    isequaln(training.condition,c) && isequaln(training.seeds,aSeed) && ...
    training.symbols==cfg.fixed_train_symbols && training.metrics.symbols==training.symbols && ...
    training.metrics.sample_count==training.symbols*(cfg.NFFT+cfg.NCP) && ...
    training.q==c.q && training.add_noise && ~training.adc_bypass && ...
    training.noise_variance==cfg.noise_variance && isequal(training.adc_range,cfg.adc_range) && ...
    all(isnan(training.error_bits)) && all(isnan(training.tested_bits)), ...
    'DMT:V2FixedTraining','Fixed synchronization did not use its declared independent training block.');
H=training.received_cross_sum./training.known_energy_sum;
assert(isequal(size(H),size(M)) && all(isfinite(H)) && all(abs(H)>0) && ...
    max(abs(H-training.H_hat))<=1e-10*max(1,max(abs(H))) && isequal(d.H_hat,training.H_hat), ...
    'DMT:V2FixedLS','Saved fixed-group LS estimate differs from training sufficient sums.');

tx=d.final_tx;
prefixHash=dmt_v13_hash(rmfield(tx,'profile_id'));
assert(isequaln(tx,d.final_rx) && strcmp(tx.stage,'fixed') && tx.round==1 && ...
    strcmp(tx.protocol,cfg.protocol) && strcmp(tx.phase,phase) && ...
    tx.condition_id==c.condition_id && tx.calibration_id==cal && ...
    tx.P_target==c.P_target && tx.q==c.q && tx.b==d.b && strcmp(tx.scheme,scheme) && ...
    strcmp(tx.authorization_basis,'fixed_profile_sync') && ...
    isequal(tx.M,M) && isequal(tx.bits_k,log2(M)) && tx.Es_reference==cfg.Es && ...
    tx.targetBER==cfg.targetBER && tx.margin_dB==cfg.margin_dB && isequal(tx.adc_range,cfg.adc_range) && ...
    strcmp(tx.profile_id,['fixed_' prefixHash]) && ...
    strcmp(tx.H_hash,dmt_v13_hash(d.H_hat)) && strcmp(tx.power_hash,dmt_v13_hash(power)) && ...
    strcmp(tx.channel_training_hash,dmt_v13_hash(training)) && ...
    ~isfield(tx,'validation_hash') && ~isfield(d,'rounds'), ...
    'DMT:V2FixedConfiguration','Fixed synchronized configuration identity differs from calibration or claims D validation.');
ack=d.ack;
assert(ack.accepted && strcmp(ack.configuration_hash,dmt_v13_hash(tx)) && ...
    strcmp(ack.profile_id,tx.profile_id) && strcmp(ack.stage,tx.stage) && ...
    ack.condition_id==c.condition_id && ack.calibration_id==cal && strcmp(ack.scheme,scheme), ...
    'DMT:V2FixedACK','ACK identity differs from the saved fixed configuration.');
f=d.feedback;
assert(f.initial_quality_scalar_count==0 && f.validation_status_entries==0 && ...
    f.loading_table_entries==0 && f.configuration_ack_count==1 && isnan(f.serialized_bits), ...
    'DMT:V2FixedOverhead','Fixed strategy claimed unnecessary loading overhead or control bit lengths.');
end

function run = dmt_t2_payload(cfg,condition,design,seeds,nSymbols)
%DMT_T2_PAYLOAD Measure payload under the declared authorization basis.
assert(isequaln(condition,design.condition) && ...
    strcmp(design.phase,seeds.phase) && strcmp(design.scheme,seeds.scheme) && ...
    design.calibration_id==seeds.calibration_id && ...
    condition.condition_id==seeds.condition_id && condition.P_target==seeds.P_target && ...
    condition.q==seeds.q && strcmp(seeds.role,'payload') && seeds.round==0 && ...
    ismember(seeds.payload_slot,1:cfg.payload_repeats), ...
    'DMT:T2PayloadIdentity','Payload stream identity differs from the frozen design.');
switch seeds.phase
    case 'preflight'
        requiredSymbols=cfg.preflight_payload_symbols;
    case 'formal'
        requiredSymbols=cfg.payload_symbols;
    otherwise
        error('DMT:T2PayloadPhase','Unsupported payload phase %s.',seeds.phase);
end
assert(nSymbols==requiredSymbols,'DMT:T2PayloadBudget', ...
    'Payload length must match the planned stage.');

switch design.scheme
    case 'ValidatedLoading'
        run=dmt_to_payload(cfg,condition,design,seeds,nSymbols);
    case {'FixedQPSK','Fixed64QAM'}
        run=measureFixed(cfg,condition,design,seeds,nSymbols);
    otherwise
        error('DMT:T2UnknownStrategy','Unknown modulation strategy: %s.',design.scheme);
end
run.phase=design.phase;
run.scheme=design.scheme;
run.calibration_id=design.calibration_id;
run.payload_slot=seeds.payload_slot;
run.design_hash=dmt_v13_hash(design);
end

function run=measureFixed(cfg,condition,design,seeds,nSymbols)
assert(strcmp(design.status,'fixed_authorized') && strcmp(design.authorization_basis,'fixed_profile_sync'), ...
    'DMT:T2FixedUnauthorized','Fixed configuration authorization is missing.');
tx=design.final_tx;
rx=design.final_rx;
ack=design.ack;
txHash=dmt_v13_hash(tx);
assert(isequaln(tx,rx) && ack.accepted && strcmp(txHash,ack.configuration_hash) && ...
    strcmp(ack.stage,'fixed') && strcmp(ack.profile_id,tx.profile_id) && ...
    ack.condition_id==condition.condition_id && ack.calibration_id==design.calibration_id && ...
    strcmp(ack.scheme,design.scheme), 'DMT:T2FixedACK', ...
    'Fixed payload requires matching local configurations and synchronization ACK.');

order=4;
if strcmp(design.scheme,'Fixed64QAM')
    order=64;
end
expectedProfile=['fixed_' dmt_v13_hash(rmfield(tx,'profile_id'))];
assert(strcmp(tx.stage,'fixed') && strcmp(tx.authorization_basis,design.authorization_basis) && ...
    strcmp(tx.profile_id,expectedProfile) && strcmp(tx.protocol,cfg.protocol) && ...
    tx.condition_id==condition.condition_id && tx.P_target==condition.P_target && ...
    tx.calibration_id==design.calibration_id && strcmp(tx.scheme,design.scheme) && ...
    strcmp(tx.phase,design.phase) && isequal(tx.M,order*ones(numel(cfg.k),1)) && ...
    isequal(tx.M,design.M) && isequal(tx.bits_k,log2(tx.M)) && ...
    tx.Es_reference==cfg.Es && tx.targetBER==cfg.targetBER && tx.margin_dB==cfg.margin_dB && ...
    tx.b==design.b && tx.b==design.power.b && tx.q==condition.q && ...
    isequal(tx.adc_range,cfg.adc_range) && ...
    abs(design.power.actual_mean-condition.P_target)/condition.P_target<=cfg.power_cal_tolerance && ...
    strcmp(tx.H_hash,dmt_v13_hash(design.H_hat)) && ...
    strcmp(tx.power_hash,dmt_v13_hash(design.power)) && ...
    strcmp(tx.channel_training_hash,dmt_v13_hash(design.Ar)) && ...
    isequaln(design.Ar.H_hat,design.H_hat) && isequal(design.Ar.M,tx.M) && ...
    design.Ar.symbols==cfg.fixed_train_symbols && design.Ar.b==tx.b, ...
    'DMT:T2FixedFreeze','Fixed profile must match the calibrated and trained configuration.');

% The fixed branch measures the complete scheduled block independently of BER.
run=dmt_to_measure(cfg,condition,tx.M,tx.b,nSymbols,seeds,'payload',design.H_hat,false,rx.M);
run.power_actual=run.metrics.tx_sum/run.metrics.sample_count;
run.power_relative_error=(run.power_actual-condition.P_target)/condition.P_target;
run.power_match=abs(run.power_relative_error)<=cfg.payload_power_tolerance;
run.configuration_hash=txHash;
run.profile_id=tx.profile_id;
run.M_hash=dmt_v13_hash(tx.M);
run.H_hash=tx.H_hash;
end

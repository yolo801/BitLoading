function report = dmt_lit7_check_link(cfg)
%DMT_LIT7_CHECK_LINK Check the production Tx, complex FFT response and ZF.
% The amplitude reduction applies only to this deterministic fixture. It
% keeps the actual bias and clipper inside their linear range.
assert(isreal(cfg.h) && all(isfinite(cfg.h)) && abs(sum(cfg.h)-1)<=1e-12 && ...
    numel(cfg.h)<=9 && cfg.NCP>=numel(cfg.h)-1 && cfg.chunkSize<=2000, ...
    'DMT:Lit7LinkGeometry','FIR gain, memory or chunk geometry is invalid.');
condition=struct('q',8);
seedA=1500000001;
seedCheck=1500000002;
trainingSymbols=7;
tailSymbols=13;
bias=1;
scale=1/4;
M=4*ones(numel(cfg.k),1);
[A,~]=dmt_v13_make_frame(cfg,M,trainingSymbols,dmt_v13_stream(cfg,seedA));
data=dmt_v13_stream(cfg,seedCheck);
[first,bitsFirst]=dmt_v13_make_frame(cfg,M,cfg.chunkSize,data);
[tail,bitsTail]=dmt_v13_make_frame(cfg,M,tailSymbols,data);

[Ytrain,metricsA,state,train]=dmt_to_link(cfg,condition,scale*A,bias,[],[],false,true);
[Yfirst,metricsFirst,state,debugFirst]=dmt_to_link(cfg,condition,scale*first,bias,state,[],false,true);
[Ytail,metricsTail,~,debugTail]=dmt_to_link(cfg,condition,scale*tail,bias,state,[],false,true);
Y=[Yfirst Ytail];
X=[first(cfg.k+1,:) tail(cfg.k+1,:)];
knownA=A(cfg.k+1,:);
Hhat=sum(Ytrain.*conj(knownA),2)./sum(abs(knownA).^2,2);
firResponse=exp(-2i*pi/cfg.NFFT*cfg.k(:)*(0:numel(cfg.h)-1))*cfg.h(:);
gain=scale*bias/(cfg.rho*cfg.sigma_ref);
Hexpected=gain*firResponse;
assert(all(abs(Hexpected)>1e-12) && all(abs(Hhat)>1e-12), ...
    'DMT:Lit7LinkNull','An active bin cannot be equalized in the noiseless fixture.');
Z=Y./Hhat;
[errors,tested]=dmt_demod_errors(cfg,Z,cellfun(@vertcat,bitsFirst,bitsTail,'UniformOutput',false),M);

% Independent direct convolution checks every sample, including those in
% the CP that are discarded later. A restarted filter could otherwise pass
% the frequency-domain comparison when CP covers its startup transient.
transmitted=[train.p;debugFirst.p;debugTail.p];
received=[train.rx_before_adc;debugFirst.rx_before_adc;debugTail.rx_before_adc];
expectedSamples=conv(transmitted,cfg.h(:));
expectedSamples=expectedSamples(1:numel(received));
resetTail=conv(debugTail.p,cfg.h(:));
tailResetDifference=max(abs(debugTail.rx_before_adc-resetTail(1:numel(debugTail.p))));
tolerance=5e-11;
metrics=[metricsA metricsFirst metricsTail];
symbolError=max(abs(Z-X),[],2);
responseError=max(abs(Y./X-Hexpected),[],2);
trainingError=abs(Hhat-Hexpected);
report=struct('engine','MATLAB production dmt_to_link', ...
    'training_data_seed',seedA,'check_data_seed',seedCheck, ...
    'training_symbols',trainingSymbols,'check_chunk_symbols',[cfg.chunkSize tailSymbols], ...
    'fft_length',cfg.NFFT,'cp_length',cfg.NCP,'first_fft_sample',cfg.NCP+1, ...
    'fir_coefficients',cfg.h(:),'fir_memory',numel(cfg.h)-1, ...
    'adc_bits_selected',condition.q,'fixture_bias',bias,'fixture_input_scale',scale, ...
    'transmitted_samples',numel(transmitted), ...
    'added_noise_energy',sum([metrics.noise_sum_sq]), ...
    'clipped_samples',sum([metrics.lower_clip_count])+sum([metrics.upper_clip_count]), ...
    'clip_error_energy',sum([metrics.clip_error_sq_sum]), ...
    'adc_bypassed',isequal([train.adc_output;debugFirst.adc_output;debugTail.adc_output],received), ...
    'convolution_max_abs_error',max(abs(received-expectedSamples)), ...
    'tail_reset_max_abs_difference',tailResetDifference,'tolerance',tolerance, ...
    'active_k',cfg.k(:),'frequency_MHz',cfg.k(:)*cfg.Fs/cfg.NFFT/1e6, ...
    'expected_fir_magnitude_dB',20*log10(abs(firResponse)), ...
    'estimated_fir_magnitude_dB',20*log10(abs(Hhat/gain)), ...
    'expected_fir_phase_deg',angle(firResponse)*180/pi, ...
    'estimated_fir_phase_deg',angle(Hhat/gain)*180/pi, ...
    'training_complex_response_error',trainingError, ...
    'check_max_complex_response_error',responseError,'check_max_zf_error',symbolError, ...
    'error_bits',errors,'tested_bits',tested);
report.passed=report.added_noise_energy==0 && report.clipped_samples==0 && ...
    report.clip_error_energy==0 && report.adc_bypassed && ...
    report.convolution_max_abs_error<=tolerance && ...
    (report.fir_memory==0 || tailResetDifference>tolerance) && ...
    all(trainingError<=tolerance) && all(responseError<=tolerance) && ...
    all(symbolError<=tolerance) && all(errors==0) && ...
    all(tested==2*(cfg.chunkSize+tailSymbols));
end

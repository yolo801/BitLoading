function checks = dmt_fb_preflight(cfg)
%DMT_FB_PREFLIGHT Validate the production link and audit arithmetic.
% These fixtures have their own data and noise seeds. Their observations
% are never used for design decisions or pooled with any payload.
assert(cfg.NFFT==64 && cfg.NCP==8 && cfg.Fs==64e6 && ...
    isequal(cfg.k(:),(1:24).') && cfg.Es==1 && isequal(cfg.Mset,[4 16 64]) && ...
    cfg.P_peak==2 && cfg.rho==4 && cfg.noise_variance==1.0491e-4 && ...
    isequal(cfg.adc_range,[-.1 2.1]) && numel(cfg.h)==9 && ...
    isreal(cfg.h) && all(isfinite(cfg.h)) && abs(sum(cfg.h)-1)<1e-12 && ...
    cfg.NCP==numel(cfg.h)-1 && cfg.chunkSize==1024 && ...
    cfg.power_cal_symbols==8192 && cfg.power_cal_tolerance==.002 && ...
    cfg.payload_power_tolerance==.01 && cfg.targetBER==1e-3 && ...
    cfg.margin_dB==1 && cfg.Wilson_z==1.96 && cfg.payload_symbols==50000 && ...
    cfg.initial_A_symbols==1024 && cfg.initial_B_symbols==2048 && ...
    cfg.design_A_symbols==1024 && cfg.design_D_symbols==8192 && cfg.control_delay==0, ...
    'DMT:FBPreflightConfig','The Fig. 7 link or frozen v2 settings differ.');
order=cfg.Mset;
link=cell(numel(order),1);
for j=1:numel(order)
    link{j}=checkNoiseless(cfg,order(j),1990000000+2*j-1,1990000000+2*j);
end
link=vertcat(link{:});
physical=checkPhysical(cfg,1990000011,1990000012);
adc=[checkADC(cfg,6);checkADC(cfg,8)];
power=checkPower(cfg,1990000060,1990000059);
counters=checkCounters(cfg);
checkpoint=checkCheckpoint(cfg);
branchFixtures=dmt_fb_promotion_fixtures(cfg);
checks=struct('scope','Mechanical fixtures. Excluded from design and formal BER.', ...
    'config_hash',dmt_v13_hash(cfg),'fir_coefficients',cfg.h(:), ...
    'fixture_seeds',[1990000001:1990000006 1990000011 1990000012 1990000059 1990000060], ...
    'link',link,'physical',physical,'adc',adc,'power',power,'counters',counters, ...
    'checkpoint',checkpoint,'branch_fixtures',branchFixtures);
checks.passed=all([link.passed]) && physical.passed && all([adc.passed]) && ...
    power.passed && counters.passed && checkpoint.passed && branchFixtures.passed;
end

function one=checkNoiseless(cfg,order,seedA,seedX)
condition=struct('q',8);
bias=1;
scale=1/4;
trainingSymbols=7;
tailSymbols=13;
M=order*ones(numel(cfg.k),1);
train=dmt_v13_make_frame(cfg,M,trainingSymbols,dmt_v13_stream(cfg,seedA));
stream=dmt_v13_stream(cfg,seedX);
[head,bits1]=dmt_v13_make_frame(cfg,M,cfg.chunkSize,stream);
[tail,bits2]=dmt_v13_make_frame(cfg,M,tailSymbols,stream);
[Ya,ma,state,da]=dmt_to_link(cfg,condition,scale*train,bias,[],[],false,true);
[Y1,m1,state,d1]=dmt_to_link(cfg,condition,scale*head,bias,state,[],false,true);
[Y2,m2,~,d2]=dmt_to_link(cfg,condition,scale*tail,bias,state,[],false,true);
known=train(cfg.k+1,:);
Hhat=sum(Ya.*conj(known),2)./sum(abs(known).^2,2);
H=((scale*bias)/(cfg.rho*cfg.sigma_ref))* ...
    (exp(-2i*pi*(cfg.k(:)/cfg.NFFT)*(0:numel(cfg.h)-1))*cfg.h(:));
assert(all(abs(H)>1e-12 & abs(Hhat)>1e-12),'DMT:FBPreflightLink', ...
    'An active frequency bin is singular in the noiseless fixture.');
X=[head(cfg.k+1,:) tail(cfg.k+1,:)];
Y=[Y1 Y2];
Z=Y./Hhat;
sent=cellfun(@vertcat,bits1,bits2,'UniformOutput',false);
[errors,tested]=dmt_demod_errors(cfg,Z,sent,M);
tx=[da.p;d1.p;d2.p];
rx=[da.rx_before_adc;d1.rx_before_adc;d2.rx_before_adc];
linear=conv(tx,cfg.h(:));
reset=conv(d2.p,cfg.h(:));
metrics=[ma m1 m2];
tolerance=5e-11;
one=struct('qam_order',order,'training_data_seed',seedA,'check_data_seed',seedX, ...
    'training_symbols',trainingSymbols,'check_chunk_symbols',[cfg.chunkSize tailSymbols], ...
    'fft_length',cfg.NFFT,'cp_length',cfg.NCP,'first_fft_sample',cfg.NCP+1, ...
    'active_k',cfg.k(:),'fixture_bias',bias,'fixture_input_scale',scale, ...
    'transmitted_samples',numel(tx),'added_noise_energy',sum([metrics.noise_sum_sq]), ...
    'clipped_samples',sum([metrics.lower_clip_count])+sum([metrics.upper_clip_count]), ...
    'clip_error_energy',sum([metrics.clip_error_sq_sum]), ...
    'adc_bypassed',isequal([da.adc_output;d1.adc_output;d2.adc_output],rx), ...
    'max_convolution_error',max(abs(rx-linear(1:numel(rx)))), ...
    'tail_state_reset_difference',max(abs(d2.rx_before_adc-reset(1:numel(d2.p)))), ...
    'training_complex_response_error',abs(Hhat-H), ...
    'check_max_complex_response_error',max(abs(Y./X-H),[],2), ...
    'check_max_zf_error',max(abs(Z-X),[],2),'error_bits',errors,'tested_bits',tested);
one.passed=one.added_noise_energy==0 && one.clipped_samples==0 && ...
    one.clip_error_energy==0 && one.adc_bypassed && ...
    one.max_convolution_error<=tolerance && one.tail_state_reset_difference>tolerance && ...
    all(one.training_complex_response_error<=tolerance) && ...
    all(one.check_max_complex_response_error<=tolerance) && ...
    all(one.check_max_zf_error<=tolerance) && all(errors==0) && ...
    all(tested==log2(order)*(cfg.chunkSize+tailSymbols));
end

function one=checkPhysical(cfg,dataSeed,noiseSeed)
q6=struct('q',6);
q8=struct('q',8);
M=repelem(cfg.Mset(:),8);
bias=1.85;
headLength=15;
tailLength=22;
symbols=headLength+tailLength;
tol=5e-11;
[total,totalBits]=dmt_v13_make_frame(cfg,M,symbols,dmt_v13_stream(cfg,dataSeed));
stream=dmt_v13_stream(cfg,dataSeed);
[head,headBits]=dmt_v13_make_frame(cfg,M,headLength,stream);
[tail,tailBits]=dmt_v13_make_frame(cfg,M,tailLength,stream);
[Y6,metrics,~,whole6]=dmt_to_link(cfg,q6,total,bias,[], ...
    dmt_v13_stream(cfg,noiseSeed),true,false);
[Y8,~,~,whole8]=dmt_to_link(cfg,q8,total,bias,[], ...
    dmt_v13_stream(cfg,noiseSeed),true,false);
noiseStream=dmt_v13_stream(cfg,noiseSeed);
[Y1,~,state,first]=dmt_to_link(cfg,q6,head,bias,[],noiseStream,true,false);
[Y2,~,~,last]=dmt_to_link(cfg,q6,tail,bias,state,noiseStream,true,false);
noiseless=conv(whole6.p,cfg.h(:));
noise=sqrt(cfg.noise_variance)*randn(dmt_v13_stream(cfg,noiseSeed),numel(whole6.p),1);
expectedAnalog=noiseless(1:numel(noise))+noise;
q6Expected=expectedADC(cfg,6,expectedAnalog);
q8Expected=expectedADC(cfg,8,expectedAnalog);
% Independent FFT indexing starts after the CP in each quantized symbol.
samples=reshape(q6Expected,cfg.NFFT+cfg.NCP,symbols);
expectedFFT=fft(samples(cfg.NCP+1:end,:),[],1)/sqrt(cfg.NFFT);
clip=min(cfg.P_peak,max(0,whole6.p_raw));
expectedRaw=bias+bias*whole6.tx_serial/(cfg.rho*cfg.sigma_ref);
% Bit draws must match exactly. Different QAM/IFFT batch sizes can round
% identical inputs differently, so record their numerical errors separately.
sameBits=cellfun(@(whole,firstBits,lastBits)isequal(whole,[firstBits;lastBits]), ...
    totalBits,headBits,tailBits);
qamError=max(abs(total-[head tail]),[],'all');
serialError=max(abs(whole6.tx_serial-[first.tx_serial;last.tx_serial]));
one=struct('data_seed',dataSeed,'noise_seed',noiseSeed,'qam_table',M,'bias',bias, ...
    'chunk_symbols',[headLength tailLength],'samples',metrics.sample_count, ...
    'clipped_samples',metrics.lower_clip_count+metrics.upper_clip_count, ...
    'expected_clipping',isequal(whole6.p,clip), ...
    'max_biased_drive_error',max(abs(whole6.p_raw-expectedRaw)), ...
    'same_chunk_bits',all(sameBits), ...
    'max_chunk_qam_error',qamError,'max_chunk_tx_serial_error',serialError, ...
    'same_chunk_inputs',all(sameBits) && qamError<=tol && serialError<=tol, ...
    'same_adc_upstream',isequal(whole6.p,whole8.p) && ...
        isequal(whole6.rx_before_adc,whole8.rx_before_adc), ...
    'same_noise',isequal(whole6.noise,whole8.noise,noise,[first.noise;last.noise]), ...
    'max_channel_noise_error',max(abs(whole6.rx_before_adc-expectedAnalog)), ...
    'max_chunk_adc_error',max(abs(whole6.adc_output-[first.adc_output;last.adc_output])), ...
    'max_q6_midrise_error',max(abs(whole6.adc_output-q6Expected)), ...
    'max_q8_midrise_error',max(abs(whole8.adc_output-q8Expected)), ...
    'max_chunk_fft_error',max(abs(Y6-[Y1 Y2]),[],'all'), ...
    'max_adc_fft_error',max(abs(Y6-expectedFFT(cfg.k+1,:)),[],'all'), ...
    'adc_resolutions_distinct',any(whole6.adc_output~=whole8.adc_output) && ...
        any(abs(Y6-Y8)>0,'all'));
one.passed=one.samples==(cfg.NCP+cfg.NFFT)*symbols && ...
    one.clipped_samples>0 && one.expected_clipping && one.same_chunk_inputs && ...
    one.same_adc_upstream && one.same_noise && one.adc_resolutions_distinct && ...
    max([one.max_biased_drive_error one.max_channel_noise_error one.max_chunk_adc_error ...
        one.max_q6_midrise_error one.max_q8_midrise_error ...
        one.max_chunk_fft_error one.max_adc_fft_error])<=tol;
end

function one=checkADC(cfg,q)
lo=cfg.adc_range(1);
hi=cfg.adc_range(2);
levels=2^q;
step=(hi-lo)/levels;
centers=lo+((0:levels-1)+.5)*step;
inputs=[lo-1 lo centers hi hi+1];
expected=[centers(1) centers(1) centers centers(end) centers(end)];
[measured,diagnostic]=dmt_to_quantize(inputs,q,cfg,false);
one=struct('q',q,'levels',diagnostic.levels,'sample_count',diagnostic.sample_count, ...
    'low_count',diagnostic.low_count,'high_count',diagnostic.high_count, ...
    'step',diagnostic.step,'unique_codes',numel(unique(measured)), ...
    'max_value_error',max(abs(measured-expected)));
one.passed=one.levels==levels && one.unique_codes==levels && one.step==step && ...
    one.low_count==1 && one.high_count==1 && one.sample_count==numel(inputs) && ...
    one.max_value_error<=10*eps(hi);
end

function output=expectedADC(cfg,q,input)
levels=2^q;
lo=cfg.adc_range(1);
step=diff(cfg.adc_range)/levels;
index=floor((input-lo)/step);
index(index<0)=0;
index(index>=levels)=levels-1;
output=lo+(index+.5)*step;
end

function one=checkPower(cfg,seed,failureSeed)
condition=struct('P_target',1.2,'q',8);
M=repelem(cfg.Mset(:),8);
power=dmt_to_power_cal(cfg,condition,M,seed);
stream=dmt_v13_stream(cfg,seed);
n=(cfg.NFFT+cfg.NCP)*cfg.power_cal_symbols;
raw=zeros(n,1);
powerSum=0;
low=0;
high=0;
last=0;
state=[];
for start=1:cfg.chunkSize:cfg.power_cal_symbols
    count=min(cfg.chunkSize,cfg.power_cal_symbols-start+1);
    X=dmt_v13_make_frame(cfg,M,count,stream);
    [~,metrics,state,debug]=dmt_to_link(cfg,condition,X,power.b,state,[],false,true);
    raw(last+(1:metrics.sample_count))=debug.tx_serial;
    last=last+metrics.sample_count;
    powerSum=powerSum+metrics.tx_sum;
    low=low+metrics.lower_clip_count;
    high=high+metrics.upper_clip_count;
end
replayed=powerSum/last;
txHash=dmt_sha256(typecast(raw,'uint8'));
fixture=cfg;
fixture.power_cal_symbols=7;
unreachable=struct('P_target',cfg.P_peak+.1,'q',8);
failureID='';
try
    dmt_to_power_cal(fixture,unreachable,M,failureSeed);
catch exception
    if ~strcmp(exception.identifier,'DMT:TOPowerUnreachable'),rethrow(exception);end
    failureID=exception.identifier;
end
one=struct('data_seed',seed,'unreachable_fixture_seed',failureSeed, ...
    'qam_table',M,'calibrated_bias',power.b,'target',condition.P_target, ...
    'relative_error',power.relative_error,'monotone',power.monotone, ...
    'reachable',power.reachable,'calibrated_mean',power.actual_mean, ...
    'independent_link_mean',replayed,'calibration_samples',power.sample_count, ...
    'link_replay_samples',last,'clip_counts',[low high], ...
    'waveform_hash',power.waveform_hash,'waveform_hash_match',strcmp(txHash,power.waveform_hash), ...
    'unreachable_failure_id',failureID);
one.passed=one.monotone && one.reachable && one.link_replay_samples==n && ...
    one.calibration_samples==n && abs(one.relative_error)<=cfg.power_cal_tolerance && ...
    abs(one.calibrated_mean-one.independent_link_mean)<5e-12 && ...
    isequal(one.clip_counts,[power.lower_clip_count power.upper_clip_count]) && ...
    one.waveform_hash_match && strcmp(one.unreachable_failure_id,'DMT:TOPowerUnreachable');
end

function one=checkCounters(cfg)
M=64*ones(numel(cfg.k),1);
n=cfg.payload_symbols*log2(M);
e1=zeros(size(n));
e2=e1;
e1(1)=1030;
e2(1)=2297;
[failed,~,low,high]=dmt_t2_adjudicate(cfg,e1+e2,n+n,true,true);
[supported,~,~,zeroUpper]=dmt_t2_adjudicate(cfg,e1*0,n+n,true,true);
edge=cfg;
edge.targetBER=zeroUpper(1);
equalThreshold=dmt_t2_adjudicate(edge,e1*0,n+n,true,true);
[badPower,berState]=dmt_t2_adjudicate(cfg,e1*0,n+n,true,false);
rates=[dmt_t2_cycle_rate(cfg,140,12288) dmt_t2_cycle_rate(cfg,142,12288) ...
    dmt_t2_cycle_rate(cfg,142,12288+9216)]/1e6;
independent=50000*[140 142 142]./((50000+[12288 12288 21504])*1.125);
one=struct('high_error_state',failed,'zero_error_state',supported, ...
    'strict_equality_state',equalThreshold,'power_mismatch_state',badPower, ...
    'ber_state_despite_power_mismatch',berState,'zero_error_upper_bound',zeroUpper(1), ...
    'sample_cycle_rates_Mbit_s',rates);
one.passed=dmt_to_count_valid(e1,n,M,cfg.payload_symbols) && ...
    dmt_to_count_valid(e2,n,M,cfg.payload_symbols) && ...
    failed=="ber_failed" && low(1)>cfg.targetBER && all(high>0) && ...
    supported=="supported" && equalThreshold=="inconclusive" && ...
    badPower=="power_mismatch" && berState=="supported" && ...
    dmt_t2_adjudicate(cfg,[],[],false,false)=="incomplete" && ...
    all(abs(zeroUpper-cfg.Wilson_z^2./(2*n+cfg.Wilson_z^2))<=10*eps(zeroUpper)) && ...
    max(abs(rates-independent))<1e-10;
end

function one=checkCheckpoint(cfg)
folder=tempname;
mkdir(folder);
closer=onCleanup(@()rmdir(folder,'s')); %#ok<NASGU>
mkdir(fullfile(folder,'checkpoints'));
p=struct('phase','preflight','source_id',dmt_v13_hash('checkpoint-fixture'), ...
    'config_id',dmt_v13_hash(cfg),'seed_id',dmt_v13_hash([101 102]));
first=struct('fixture_slot',1,'tested_bits',[62;62],'error_bits',[0;3]);
second=struct('fixture_slot',2,'tested_bits',[62;62],'error_bits',[1;0]);
dmt_t2_record('save',folder,p,'Payload',1,first);
firstPath=fullfile(folder,'checkpoints','payload_0001.mat');
before=dmt_fb_filehash(firstPath);

% The resumed view retrieves the committed slot and sees the second as
% missing. Fill only the missing slot and prove the first file is unchanged.
reopened=dmt_t2_record('load',folder,p,'Payload',1,[]);
missing=dmt_t2_record('load',folder,p,'Payload',2,[]);
if isempty(missing)
    dmt_t2_record('save',folder,p,'Payload',2,second);
end
after=dmt_fb_filehash(firstPath);
secondRead=dmt_t2_record('load',folder,p,'Payload',2,[]);
overwriteID='';
try
    dmt_t2_record('save',folder,p,'Payload',1,second);
catch exception
    if ~strcmp(exception.identifier,'DMT:V2Overwrite'),rethrow(exception);end
    overwriteID=exception.identifier;
end
wrong=p;
wrong.seed_id=dmt_v13_hash([101 103]);
identityID='';
try
    dmt_t2_record('load',folder,wrong,'Payload',1,[]);
catch exception
    if ~strcmp(exception.identifier,'DMT:V2Checkpoint'),rethrow(exception);end
    identityID=exception.identifier;
end
one=struct('first_reopened',isequaln(first,reopened), ...
    'second_absent_before_resume',isempty(missing),'second_committed',isequaln(second,secondRead), ...
    'first_preserved',strcmp(before,after) && strcmp(before,dmt_fb_filehash(firstPath)), ...
    'checkpoint_count',numel(dir(fullfile(folder,'checkpoints','*.mat'))), ...
    'overwrite_guard_id',overwriteID,'identity_guard_id',identityID);
one.passed=one.first_reopened && one.second_absent_before_resume && one.second_committed && ...
    one.first_preserved && one.checkpoint_count==2 && ...
    strcmp(overwriteID,'DMT:V2Overwrite') && strcmp(identityID,'DMT:V2Checkpoint');
end

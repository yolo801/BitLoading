function linkHash=dmt_fb_audit_gates(folder,p)
%DMT_FB_AUDIT_GATES Check portable preflight and ordered-run attestations.
path=fullfile(folder,'mechanical_checks.mat');
loaded=load(path,'checkpoint');
cfg=p.cfg;
m=loaded.checkpoint;
assert(m.passed && strcmp(m.config_hash,dmt_v13_hash(cfg)) && ...
    isequal(m.fir_coefficients,cfg.h(:)) && ...
    isequal(sort([m.link.qam_order]),[4 16 64]) && all([m.link.passed]) && ...
    isequal(sort([m.adc.q]),[6 8]) && all([m.adc.passed]) && ...
    m.physical.passed && m.power.passed && m.counters.passed && ...
    m.checkpoint.passed && m.branch_fixtures.passed, ...
    'DMT:FBAuditMechanical','Production preflight did not pass the frozen model and branch fixtures.');
for r=reshape(m.link,1,[])
    assert(r.fft_length==cfg.NFFT && r.cp_length==cfg.NCP && ...
        r.first_fft_sample==cfg.NCP+1 && isequal(r.active_k,cfg.k(:)) && ...
        r.training_symbols==7 && isequal(r.check_chunk_symbols,[cfg.chunkSize 13]) && ...
        r.transmitted_samples==(r.training_symbols+sum(r.check_chunk_symbols))*(cfg.NFFT+cfg.NCP) && ...
        r.added_noise_energy==0 && r.clipped_samples==0 && r.clip_error_energy==0 && ...
        r.adc_bypassed && r.max_convolution_error<=5e-11 && r.tail_state_reset_difference>5e-11 && ...
        boundedCarrier(r.training_complex_response_error,cfg,5e-11) && ...
        boundedCarrier(r.check_max_complex_response_error,cfg,5e-11) && ...
        boundedCarrier(r.check_max_zf_error,cfg,5e-11) && boundedCarrier(r.error_bits,cfg,0) && ...
        isequal(r.tested_bits,sum(r.check_chunk_symbols)*log2(r.qam_order)*ones(numel(cfg.k),1)), ...
        'DMT:FBAuditMechanical','Noiseless preflight record for %d-QAM contradicts its gate.',r.qam_order);
end
linkHash=dmt_fb_filehash(path);
if p.test_only,return;end
gate=checkGate(folder,p,p.preflight_gate,'preflight_gate_receipt.mat',p.study,'preflight');
assert(strcmp(gate.mechanical_sha256,linkHash), ...
    'DMT:FBAuditGate','Copied mechanical checks do not match the passed preflight.');
if strcmp(p.study,'scan')
    gate=checkGate(folder,p,p.promotion_gate,'promotion_gate_receipt.mat','promotion','formal');
    assert(gate.figures_valid && gate.planned==20 && gate.symbols_per_slot==50000, ...
        'DMT:FBAuditGate','The prerequisite promotion study did not complete its full formal budget.');
end
end

function yes=boundedCarrier(value,cfg,limit)
yes=isequal(size(value),[numel(cfg.k) 1]) && all(value>=0 & value<=limit);
end

function receipt=checkGate(folder,p,g,name,study,phase)
assert(strcmp(g.study,study) && strcmp(g.phase,phase) && strcmp(g.source_id,p.source_id), ...
    'DMT:FBAuditGate','Gate attestation has unexpected study, phase or source.');
path=fullfile(folder,name);
assert(strcmp(dmt_fb_filehash(path),g.receipt_sha256), ...
    'DMT:FBAuditGate','Copied gate receipt differs: %s.',name);
loaded=load(path,'checkpoint');
receipt=loaded.checkpoint;
assert(strcmp(receipt.study,study) && strcmp(receipt.phase,phase) && ...
    strcmp(receipt.source_id,p.source_id) && receipt.test_only==strcmp(phase,'preflight') && ...
    receipt.valid && receipt.data_integrity_valid && receipt.acquisition_complete, ...
    'DMT:FBAuditGate','Archived gate receipt did not complete and pass %s/%s.',study,phase);
end

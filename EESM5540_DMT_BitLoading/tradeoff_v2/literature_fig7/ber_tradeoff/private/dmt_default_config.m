function cfg = dmt_default_config()
%DMT_DEFAULT_CONFIG Physical spec v1.0; execution protocol v1.1.
cfg.specVersion = '1.0';
cfg.protocolVersion = '1.1';
cfg.NFFT = 64;
cfg.NCP = 8;
cfg.Fs = 64e6;
cfg.k = (1:24).'; % Mathematical k; positive-frequency MATLAB row is k+1.
cfg.Es = 1;
cfg.Mset = [4 16 64];
cfg.h = [0.25 0.5 0.25]; % DC gain one: do NOT energy-normalize this FIR.
cfg.sigma_w2 = 10^(-29/10);
cfg.rho_ref_dB = 10*log10(cfg.Es/cfg.sigma_w2);
cfg.targetBER = 1e-3;
cfg.margin_dB = 1;
cfg.trainSymbols = 1024;
cfg.probeSymbols = 2048;
cfg.mainSymbols = 100000;
cfg.smokeSymbols = 2000;
cfg.chunkSize = 2000;
cfg.seeds = [11 22 33];
cfg.trainDataSeed = 1701;
cfg.trainNoiseSeed = 2701;
cfg.probeDataSeed = 1702;
cfg.probeNoiseSeed = 2702;
cfg.selfTrainSeed = 1601;
cfg.selfPayloadSeeds = [1611 1612 1613];
cfg.selfNoiseSeed = 1609;
cfg.streamType = 'mt19937ar';
cfg.mainSeedBase = 100000;
cfg.smokeSeedBase = 300000;
cfg.Tu = cfg.NFFT/cfg.Fs;
cfg.TCP = cfg.NCP/cfg.Fs;
cfg.Ts = cfg.Tu + cfg.TCP;
cfg.expectedUsefulEnergy = 2*numel(cfg.k)*cfg.Es;
cfg.expectedPower = cfg.expectedUsefulEnergy/cfg.NFFT;
cfg.expectedCPEnergy = cfg.expectedPower*cfg.NCP;
cfg.expectedTotalEnergy = cfg.expectedPower*(cfg.NFFT+cfg.NCP);
assert(cfg.NCP >= numel(cfg.h)-1, 'CP must cover the FIR memory.');
assert(cfg.chunkSize <= 2000, 'Chunk size exceeds the frozen limit.');
end

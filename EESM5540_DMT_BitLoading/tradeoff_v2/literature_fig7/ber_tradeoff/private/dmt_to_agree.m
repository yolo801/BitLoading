function [tx,rx,ack] = dmt_to_agree(cfg,configuration)
%DMT_TO_AGREE Separate local value copies and ideal configuration ACK.
% Candidate agreement confirms a full table before its physical calibration;
% only stage=accepted plus a completed D design can authorize payload.
required={'protocol','condition_id','P_target','q','calibration_id','scheme', ...
    'phase','stage','round','profile_id','M','bits_k','Es_reference', ...
    'targetBER','margin_dB','adc_range','initial_shared_hash'};
assert(isstruct(configuration) && isscalar(configuration) && all(isfield(configuration,required)));
assert(strcmp(configuration.protocol,cfg.protocol) && ...
    any(strcmp(configuration.scheme,cfg.scheme_names)) && ...
    any(strcmp(configuration.phase,{'preflight','formal'})) && ...
    any(strcmp(configuration.stage,{'candidate','accepted'})));
M=configuration.M(:);
assert(numel(M)==numel(cfg.k) && all(ismember(M,cfg.Mset)) && ...
    isequal(configuration.bits_k(:),log2(M)) && configuration.Es_reference==cfg.Es && ...
    configuration.targetBER==cfg.targetBER && configuration.margin_dB==cfg.margin_dB);
assert(ismember(configuration.P_target,cfg.P_targets) && ...
    ismember(configuration.q,cfg.adc_bits) && isequal(configuration.adc_range,cfg.adc_range));
if strcmp(configuration.scheme,'UniformAdaptive'),assert(all(M==M(1)));end
if strcmp(configuration.stage,'accepted')
    assert(all(isfield(configuration,{'b','H_hash','power_hash','validation_hash','channel_training_hash'})));
    assert(isscalar(configuration.b) && isfinite(configuration.b) && ...
        configuration.b>=cfg.b_bounds(1) && configuration.b<=cfg.b_bounds(2));
    hashes={configuration.H_hash,configuration.power_hash,configuration.validation_hash, ...
        configuration.channel_training_hash};
    assert(all(cellfun(@(v)ischar(v)&&numel(v)==64,hashes)));
end
tx=configuration;
advertisedHash=dmt_v13_hash(tx);
rx=tx; % MATLAB struct value copy, then independently checked at the receiver.
assert(isequaln(tx,rx) && strcmp(dmt_v13_hash(rx),advertisedHash));
ack=struct('accepted',true,'configuration_hash',advertisedHash, ...
    'stage',rx.stage,'profile_id',rx.profile_id,'condition_id',rx.condition_id, ...
    'calibration_id',rx.calibration_id,'scheme',rx.scheme);
end

function dmt_vm_payload_check(m,cfg,c,design,seeds,n)
%DMT_VM_PAYLOAD_CHECK Audit saved receiver counts and payload authorization.
assert(strcmp(design.status,'accepted') && strcmp(m.phase,seeds.phase) && ...
    strcmp(m.role,'payload') && isequaln(m.condition,c) && isequaln(m.seeds,seeds) && ...
    m.calibration_id==seeds.calibration_id && m.payload_slot==seeds.payload_slot && ...
    strcmp(m.scheme,seeds.scheme) && strcmp(m.design_hash,dmt_v13_hash(design)) && ...
    strcmp(m.configuration_hash,dmt_v13_hash(design.final_tx)) && ...
    strcmp(m.profile_id,design.final_tx.profile_id) && isequal(m.M,design.M) && ...
    isequal(m.M_rx,design.M) && isequal(m.H_used,design.H_hat) && isequal(m.H_hat,design.H_hat) && ...
    m.b==design.b && m.q==c.q && m.add_noise && ~m.adc_bypass && ...
    m.noise_variance==cfg.noise_variance && isequal(m.adc_range,cfg.adc_range) && ...
    ~m.training && m.symbols==n && m.nSymbols_requested==n, ...
    'DMT:VMPayloadIdentity','Payload evidence differs from the accepted configuration or plan.');
[valid,why]=dmt_to_count_valid(m.error_bits,m.tested_bits,m.M,n);
assert(valid,'DMT:VMPayloadCount','%s',why);
metrics=m.metrics;
samples=n*(cfg.NFFT+cfg.NCP);
power=metrics.tx_sum/samples;
clip=metrics.lower_clip_count+metrics.upper_clip_count;
adc=metrics.adc_low_count+metrics.adc_high_count;
assert(metrics.symbols==n && metrics.sample_count==samples && ...
    sum(metrics.tx_hist_counts)==samples && all(metrics.tx_hist_counts>=0 & ...
    metrics.tx_hist_counts==fix(metrics.tx_hist_counts)) && ...
    isfinite(power) && power>=0 && power<=cfg.P_peak && metrics.tx_min>=0 && metrics.tx_max<=cfg.P_peak && ...
    all(isfinite([clip,adc])) && all([clip,adc]>=0 & [clip,adc]<=samples) && ...
    m.power_actual==power && m.power_relative_error==(power-c.P_target)/c.P_target && ...
    m.power_match==(abs(m.power_relative_error)<=cfg.payload_power_tolerance), ...
    'DMT:VMPayloadPower','Sample, histogram, power or clipping counts are inconsistent.');
end

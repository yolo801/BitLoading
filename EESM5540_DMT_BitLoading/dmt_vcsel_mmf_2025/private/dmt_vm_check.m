function dmt_vm_check(kind,item,cfg,condition,calID,scheme,slot,phase,plan,parent)
% Read-only audit of shared probe evidence and each complete candidate.
assert(isnan(slot) && isstruct(item) && isscalar(item) && ...
    isequaln(item.condition,condition) && item.calibration_id==calID && ...
    strcmp(item.phase,phase) && all(plan.phase==string(phase)), ...
    'DMT:VMRecord','Saved calibration does not match its planned identity.');
switch kind
    case 'Shared'
        checkShared();
    case 'Design'
        checkDesign();
    otherwise
        error('DMT:VMRecordKind','Unsupported candidate record kind %s.',kind);
end

    function checkShared()
        assert(strcmp(item.status,'complete'));
        M0=4*ones(numel(cfg.k),1);
        assert(isequal(item.M0,M0),'DMT:VMProbeOrder','The shared probe must use QPSK.');
        power(item.power0,M0,'Shared',0,'initial_power');
        block(item.A0,M0,item.power0.b,'Shared',0,'A0',cfg.initial_A_symbols,[]);
        block(item.B0,M0,item.power0.b,'Shared',0,'B0',cfg.initial_B_symbols,item.A0.H_hat);
        assert(isequaln(item.H0,item.A0.H_hat) && isequaln(item.gamma_B,item.B0.gamma));
        expected=struct('condition_id',condition.condition_id,'P_target',condition.P_target, ...
            'case_id',condition.case_id,'swing',condition.swing,'q',condition.q, ...
            'calibration_id',calID,'phase',phase,'active_k',cfg.k(:),'Es_reference',cfg.Es, ...
            'gamma_B',item.B0.gamma(:));
        h=dmt_v13_hash(expected);
        assert(isequaln(item.feedback_sent,expected) && isequaln(item.feedback_received,expected) && ...
            strcmp(item.feedback_hash_sent,h) && strcmp(item.feedback_hash_received,h), ...
            'DMT:VMProbeFeedback','Saved feedback differs from independent B0 or contains extra fields.');
    end

    function checkDesign()
        assert(strcmp(item.scheme,scheme) && isstruct(parent) && strcmp(parent.status,'complete') && ...
            isequaln(parent.condition,condition) && parent.calibration_id==calID && ...
            strcmp(item.initial_shared_hash,dmt_v13_hash(parent)) && ...
            isequaln(item.initial_gamma_B,parent.gamma_B));
        proposal=dmt_vm_decisions(cfg,scheme,parent.gamma_B);
        expected=proposal.M;
        assert(isequal(item.initial_M,expected) && isequal(item.initial_allowed,proposal.allowed));
        near(item.predicted_BER_design,proposal.predicted);
        nRounds=numel(item.rounds);
        assert(nRounds>=1 && nRounds<=cfg.max_rounds);
        for r=1:nRounds
            one=item.rounds(r);
            assert(one.round==r && isequal(one.M,expected), ...
                'DMT:VMCandidate','Strategy attempted an unplanned candidate.');
            agreement(one.candidate_tx,one.candidate_rx,one.candidate_ack,one.M,'candidate',r);
            power(one.power,one.M,scheme,r,'power');
            block(one.Ar,one.M,one.power.b,scheme,r,'Ar',cfg.design_A_symbols,[]);
            block(one.Dr,one.M,one.power.b,scheme,r,'Dr',cfg.design_D_symbols,one.Ar.H_hat);
            [low,high]=dmt_wilson(one.Dr.error_bits,one.Dr.tested_bits);
            [lowCheck,highCheck]=independentWilson(one.Dr.error_bits,one.Dr.tested_bits);
            assert(all(abs(one.CI_low-lowCheck)<=3e-15 & abs(one.CI_high-highCheck)<=3e-15), ...
                'DMT:VMValidationWilson','Stored validation intervals differ from actual carrier counters.');
            decision=dmt_vm_decisions(cfg,scheme,[],one.M,low,high,r);
            assert(isequal(one.supported_k,decision.supported_k) && ...
                strcmp(one.status,decision.status) && strcmp(one.reason,decision.reason) && ...
                isequal(one.proposed_next_M,decision.next_M) && decision.terminal==(r==nRounds), ...
                'DMT:VMValidationDecision','Saved validation disposition or next table differs.');
            expected=decision.next_M;
        end
        assert(strcmp(item.status,decision.status) && strcmp(item.reason,decision.reason));
        if decision.accepted
            assert(isequal(item.M,one.M) && item.b==one.power.b && isequal(item.H_hat,one.Ar.H_hat));
            t=item.final_tx;
            agreement(t,item.final_rx,item.ack,item.M,'accepted',nRounds);
            assert(t.b==item.b && strcmp(t.H_hash,dmt_v13_hash(item.H_hat)) && ...
                strcmp(t.power_hash,dmt_v13_hash(one.power)) && strcmp(t.validation_hash,dmt_v13_hash(one.Dr)) && ...
                strcmp(t.channel_training_hash,dmt_v13_hash(one.Ar)));
        else
            assert(isempty(item.M) && isempty(item.b) && isempty(item.H_hat) && ...
                isempty(fieldnames(item.final_tx)) && isempty(fieldnames(item.final_rx)) && ...
                isempty(fieldnames(item.ack)),'DMT:VMRejectedDesign','Rejected design has frozen payload settings.');
        end
        f=item.feedback;
        k=numel(cfg.k);
        assert(f.initial_quality_scalar_count==k && f.validation_status_entries==nRounds*k && ...
            f.loading_table_entries==(nRounds+decision.accepted)*k && ...
            f.configuration_ack_count==nRounds+decision.accepted && isnan(f.serialized_bits));
        c=item.costs;
        near(c.power_seconds,sum(arrayfun(@(r)r.power.compute_seconds,item.rounds)));
        near(c.training_seconds,sum(arrayfun(@(r)r.Ar.compute_seconds,item.rounds)));
        near(c.validation_seconds,sum(arrayfun(@(r)r.Dr.compute_seconds,item.rounds)));
        assert(all(isfinite([c.loading_seconds,c.design_seconds])) && ...
            c.loading_seconds>=0 && c.design_seconds>=0);
    end

    function agreement(tx,rx,ack,M,stage,r)
        [reTx,reRx,reAck]=dmt_vm_agree(cfg,tx);
        unsigned=dmt_v13_hash(rmfield(tx,'profile_id'));
        expectedID=sprintf('c%02d_cal%02d_%s_r%02d_%s_%s',condition.condition_id,calID, ...
            scheme,r,stage,unsigned(1:12));
        assert(isequaln(tx,reTx) && isequaln(rx,reRx) && isequaln(ack,reAck) && ...
            tx.condition_id==condition.condition_id && tx.calibration_id==calID && ...
            strcmp(tx.phase,phase) && strcmp(tx.scheme,scheme) && strcmp(tx.stage,stage) && ...
            tx.round==r && isequal(tx.M,M) && strcmp(tx.profile_id,expectedID) && ...
            strcmp(tx.initial_shared_hash,item.initial_shared_hash) && ...
            ~any(isfield(tx,{'H_hat','H0','error_bits','tested_bits'})), ...
            'DMT:VMAgreement','Saved configuration or receiver ACK differs from candidate identity.');
    end

    function power(p,M,name,r,role)
        seed=dmt_to_seed(plan,condition.condition_id,calID,name,r,role,NaN);
        assert(isnan(seed.noise_seed) && p.seed==seed.data_seed && p.data_seed==seed.data_seed && ...
            isequal(p.M,M) && p.target==condition.P_target && p.reachable && p.monotone && ...
            p.symbols==cfg.power_cal_symbols && p.sample_count==p.symbols*(cfg.NFFT+cfg.NCP) && ...
            p.commanded_swing==condition.swing && p.commanded_peak==condition.swing*condition.P_target && ...
            p.b>=cfg.b_bounds(1) && p.b<=cfg.b_bounds(2) && ...
            abs((p.actual_mean-p.target)/p.target)<=cfg.power_cal_tolerance && ...
            abs(p.tx_sum/p.sample_count-p.actual_mean)<=5e-12 && ...
            ischar(p.waveform_hash) && ~isempty(regexp(p.waveform_hash,'^[a-f0-9]{64}$','once')) && ...
            isfinite(p.compute_seconds) && p.compute_seconds>=0, ...
            'DMT:VMPower','Calibration differs from its independent seed, TX samples or locked tolerance.');
    end

    function block(m,M,b,name,r,role,n,H)
        seed=dmt_to_seed(plan,condition.condition_id,calID,name,r,role,NaN);
        assert(isequaln(m.condition,condition) && strcmp(m.phase,phase) && strcmp(m.role,role) && ...
            isequaln(m.seeds,seed) && isequal(m.M,M) && isequal(m.M_rx,M) && m.b==b && ...
            m.q==condition.q && m.add_noise && m.noise_variance==cfg.noise_variance && ...
            ~m.adc_bypass && isequal(m.adc_range,cfg.adc_range) && m.symbols==n && ...
            m.nSymbols_requested==n && m.metrics.symbols==n && ...
            m.metrics.sample_count==n*(cfg.NFFT+cfg.NCP) && ...
            validMetricCounts(m.metrics,cfg.P_peak) && isfinite(m.compute_seconds) && m.compute_seconds>=0, ...
            'DMT:VMBlock','Saved pilot or validation block differs from planned timing, stream or settings.');
        assert(isequal(size(m.known_energy_sum),size(M),size(m.received_energy_sum),size(m.received_cross_sum)) && ...
            all(m.known_energy_sum>0 & isfinite(m.known_energy_sum)) && ...
            all(m.received_energy_sum>=0 & isfinite(m.received_energy_sum)) && ...
            all(isfinite(m.received_cross_sum)));
        if isempty(H)
            assert(m.training && isempty(m.H_used) && all(isnan(m.error_bits)) && all(isnan(m.tested_bits)));
            near(m.H_hat,m.received_cross_sum./m.known_energy_sum);
            assert(all(abs(m.H_hat)>0));
        else
            assert(~m.training && isequal(m.H_hat,H) && isequal(m.H_used,H));
            residual=m.received_energy_sum./abs(H).^2+m.known_energy_sum-2*real(m.received_cross_sum./H);
            near(m.residual_sum_sq,residual);
            near(m.gamma,m.known_energy_sum./m.residual_sum_sq);
            [ok,why]=dmt_to_count_valid(m.error_bits,m.tested_bits,M,n);
            assert(ok,'DMT:VMBlockCounts','%s',why);
        end
    end
end

function valid=validMetricCounts(m,peak)
clips=[m.lower_clip_count,m.upper_clip_count,m.adc_low_count,m.adc_high_count];
valid=all(isfinite(clips) & clips>=0 & clips==fix(clips)) && ...
    sum(clips(1:2))<=m.sample_count && sum(clips(3:4))<=m.sample_count && ...
    m.tx_min>=0 && m.tx_min<=m.tx_max && m.tx_max<=peak;
end

function [low,high]=independentWilson(e,n)
z=1.96;
center=(e+z*z/2)./(n+z*z);
radius=z*sqrt(e.*(1-e./n)+z*z/4)./(n+z*z);
low=max(0,center-radius);
high=min(1,center+radius);
end

function near(a,b)
assert(isequal(size(a),size(b)) && all(isfinite(a(:))) && all(isfinite(b(:))) && ...
    all(abs(a(:)-b(:))<=1e-9*max(1,abs(b(:)))), ...
    'DMT:VMRecomputed','Saved reported quantity differs from checkpoint-derived value.');
end

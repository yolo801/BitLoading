function hash=dmt_vm_gates(folder,p)
% Authenticate the real preflight and both archived execution gates.
path=fullfile(folder,'mechanical_checks.mat');
record=load(path,'checkpoint');
m=record.checkpoint;
cfg=p.cfg;
assert(m.passed && strcmp(m.config_hash,p.config_id) && ...
    strcmp(m.conditions_hash,dmt_v13_hash(cfg.conditions)) && ...
    isequal(sortrows([[m.link.case_id].',[m.link.qam_order].']),[1 4;1 16;1 64;2 4;2 16;2 64]) && ...
    numel(m.power)==numel(cfg.conditions) && all([m.power.passed]) && ...
    m.physical.passed && m.adc.passed && m.unreachable_power.passed && ...
    m.counters.passed && m.checkpoint.passed && m.strategy.passed, ...
    'DMT:VMMechanicalGate','Frozen MATLAB mechanical or strategy preflight failed.');
for r=reshape(m.link,1,[])
    c=cfg.conditions([cfg.conditions.case_id]==r.case_id & [cfg.conditions.swing]==.5);
    limit=5e-10;
    assert(r.passed && r.fft_length==cfg.NFFT && r.cp_length==cfg.NCP && r.first_fft_sample==cfg.NCP+1 && ...
        r.fir_memory==numel(c.h)-1 && r.fir_memory<=cfg.NCP && isequal(r.active_k,cfg.k(:)) && ...
        r.hermitian && r.empty_dc_nyquist_guard && r.adc_bypassed && ...
        r.clipped_samples==0 && r.added_noise_energy==0 && ...
        r.max_convolution_error<=limit && r.tail_state_reset_difference>limit && ...
        bounded(r.training_complex_response_error,cfg,limit) && ...
        bounded(r.data_complex_response_error,cfg,limit) && bounded(r.max_zf_error,cfg,limit) && ...
        bounded(r.error_bits,cfg,0) && ...
        isequal(r.tested_bits,sum(r.data_chunk_symbols)*log2(r.qam_order)*ones(numel(cfg.k),1)), ...
        'DMT:VMLinkGate','Noiseless receiver evidence for a Case/QAM pair failed.');
end
hash=dmt_fb_filehash(path);
if ~strcmp(p.phase,'preflight')
    checkGate(folder,p,p.preflight_gate,'preflight',hash,0);
end
if strcmp(p.phase,'formal')
    checkGate(folder,p,p.pilot_gate,'pilot',hash,24);
end
end

function yes=bounded(values,cfg,limit)
yes=isequal(size(values),[numel(cfg.k),1]) && all(values>=0 & values<=limit);
end

function checkGate(folder,p,gate,phase,mechanicalHash,budget)
path=fullfile(folder,[phase '_gate_receipt.mat']);
assert(strcmp(gate.phase,phase) && strcmp(gate.receipt_sha256,dmt_fb_filehash(path)) && ...
    strcmp(gate.mechanical_sha256,mechanicalHash),'DMT:VMGateEvidence','%s gate receipt bytes changed.',phase);
record=load(path,'checkpoint');
r=record.checkpoint;
assert(r.valid && r.data_integrity_valid && r.acquisition_complete && strcmp(r.phase,phase) && ...
    strcmp(r.source_id,p.source_id) && strcmp(r.config_id,p.config_id) && ...
    strcmp(r.mechanical_sha256,mechanicalHash) && r.planned==budget, ...
    'DMT:VMGateEvidence','Saved %s phase is incompatible or incomplete.',phase);
end
